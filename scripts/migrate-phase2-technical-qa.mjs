import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const files = [
  'content/catalog-manifest.json',
  'content/phase-2-manifest.json',
  'content/catalog-manifest-phase-2-draft.json',
  'content/content-registry-phase-2.json',
  'content/content-registry-phase-2-draft.json',
];

const obsoleteFields = [
  'pixel_qa_status',
  'pixel_qa_notes',
  'pixel_qa_failure_reasons',
  'pixel_grid_width',
  'pixel_grid_height',
  'pixel_region_count',
  'pixel_tiny_region_count',
  'pixel_transition_ratio',
  'pixel_dominant_color_ratio',
  'pixel_palette_size',
];
const obsoleteReasons = new Set([
  'REJECT_PIXEL_NOISE',
  'REJECT_MICRO_DETAIL',
  'REJECT_WEAK_PIXEL_SILHOUETTE',
  'REJECT_COLOR_MUD',
  'REJECT_TOO_MANY_SMALL_OBJECTS',
  'REJECT_PIXELIZED_SUBJECT_LOSS',
  'REJECT_BACKGROUND_TOO_BUSY',
]);

function cleanEntry(entry) {
  const cleaned = { ...entry };
  obsoleteFields.forEach((field) => delete cleaned[field]);
  if (Array.isArray(cleaned.negative_constraints)) {
    cleaned.negative_constraints = cleaned.negative_constraints.filter((reason) => !obsoleteReasons.has(reason));
  }
  return cleaned;
}

function cleanDocument(value) {
  if (Array.isArray(value)) return value.map(cleanEntry);
  const cleaned = { ...value };
  if (cleaned.pixelization_qa || cleaned.pixelization_pipeline) {
    const previous = cleaned.pixelization_pipeline || cleaned.pixelization_qa;
    cleaned.pixelization_pipeline = {
      pipeline: previous.pipeline || 'catalog-ingestion-grid-preview-v1',
      reference: previous.reference || 'actual runtime logical cell map generated by catalog ingestion',
      player_mode: previous.player_mode || 'legacy/classic cell renderer',
      cell_render_size_css_px: previous.cell_render_size_css_px || 32,
      grid_by_orientation: previous.grid_by_orientation || { portrait: '64x80', square: '64x64', landscape: '80x60' },
      pixel_preview_asset: previous.pixel_preview_asset || 'preview_asset',
      purpose: 'runtime processing and catalog integration; no per-asset visual QA gate',
      optional_spot_checks: 'sampled sanity checks only; never a per-asset acceptance condition',
    };
    delete cleaned.pixelization_qa;
  }
  for (const key of ['entries', 'covers']) {
    if (Array.isArray(cleaned[key])) cleaned[key] = cleaned[key].map(cleanEntry);
  }
  if (cleaned.cover_plan?.entries) {
    cleaned.cover_plan = { ...cleaned.cover_plan, entries: cleaned.cover_plan.entries.map(cleanEntry) };
  }
  return cleaned;
}

for (const relativePath of files) {
  const filePath = resolve(root, relativePath);
  const value = JSON.parse(await readFile(filePath, 'utf8'));
  await writeFile(filePath, `${JSON.stringify(cleanDocument(value), null, 2)}\n`, 'utf8');
}

console.log(JSON.stringify({ migrated_files: files.length, per_asset_visual_gate: 'removed', obsolete_reasons_removed: obsoleteReasons.size }, null, 2));
