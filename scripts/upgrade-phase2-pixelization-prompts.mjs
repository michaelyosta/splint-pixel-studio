import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const manifestPaths = [
  resolve(root, 'content/phase-2-manifest.json'),
  resolve(root, 'content/catalog-manifest-phase-2-draft.json'),
];

const pixelizationBlock = [
  'Pixelization-first design: preserve the story, silhouette, and major color masses on the actual Splint logical grid.',
  'Use 1–3 focal elements, clear foreground/midground/background separation, broad readable shapes, strong warm/cool contrast, and restrained decoration.',
  'Avoid micro-texture, thin wires, tiny lettering, dense foliage, repeated small objects, narrow slivers, and busy backgrounds that collapse into noise after quantization.',
  'The full-color master and its 64×80 portrait, 64×64 square, or 80×60 landscape logical-grid preview must both remain immediately readable in 1–2 seconds.',
].join(' ');
function upgrade(document) {
  const entries = document.entries.map((entry) => ({
    ...entry,
    generation_prompt: entry.generation_prompt.includes('Pixelization-first design:')
      ? entry.generation_prompt
      : `${entry.generation_prompt}\n${pixelizationBlock}`,
  }));
  const covers = (document.cover_plan?.entries || []).map((cover) => ({
    ...cover,
    generation_prompt: cover.generation_prompt.includes('Pixelization-first design:')
      ? cover.generation_prompt
      : `${cover.generation_prompt}\n${pixelizationBlock}`,
  }));
  return {
    ...document,
    pixelization_pipeline: {
      pipeline: 'catalog-ingestion-grid-preview-v1',
      reference: 'actual runtime logical cell map generated by catalog ingestion',
      player_mode: 'legacy/classic cell renderer',
      cell_render_size_css_px: 32,
      grid_by_orientation: { portrait: '64x80', square: '64x64', landscape: '80x60' },
      pixel_preview_asset: 'preview_asset',
      purpose: 'runtime processing and catalog integration; no per-asset visual QA gate',
      optional_spot_checks: 'sampled sanity checks only; never a per-asset acceptance condition',
      ...(document.pixelization_pipeline || {}),
    },
    cover_plan: document.cover_plan ? { ...document.cover_plan, entries: covers } : document.cover_plan,
    entries,
    updated_at: new Date().toISOString(),
  };
}

for (const filePath of manifestPaths) {
  const document = JSON.parse(await readFile(filePath, 'utf8'));
  await writeFile(filePath, `${JSON.stringify(upgrade(document), null, 2)}\n`, 'utf8');
}

console.log(JSON.stringify({ upgraded_manifests: manifestPaths.length, pixelization_block: 'applied', per_asset_visual_gate: 'removed' }, null, 2));
