/** Server-side derivation for one of the planner's bounded target options. */
export async function deriveSparkChanges(db, {
  userId, template, target, maxChanges = SPARK_TARGET_MAX_CELLS,
} = {}) {
  const bounds = getTileBounds({
    width: Number(template.width),
    height: Number(template.height),
    tileSize: Number(template.tile_size || 32),
    tileX: Number(target.tile_x),
    tileY: Number(target.tile_y),
  });
  const row = await db.get(
    'SELECT cells_json, width, height FROM coloring_template_tiles WHERE template_id=? AND tile_x=? AND tile_y=?',
    [template.id, bounds.tile_x, bounds.tile_y],
  );
  if (!row) return [];
  const progress = await db.get(
    'SELECT filled_json FROM coloring_tiled_progress_tiles WHERE user_id=? AND template_id=? AND tile_x=? AND tile_y=?',
    [userId, template.id, bounds.tile_x, bounds.tile_y],
  );
  const cells = parseJsonArray(row.cells_json) || [];
  const filled = parseJsonArray(progress?.filled_json) || Array(bounds.cell_count).fill(-1);
  const box = target.bounds || {};
  const minX = Math.max(bounds.offset_x, Number(box.min_x) || bounds.offset_x);
  const minY = Math.max(bounds.offset_y, Number(box.min_y) || bounds.offset_y);
  const maxX = Math.min(bounds.offset_x + bounds.width - 1, Number(box.max_x) || bounds.offset_x + bounds.width - 1);
  const maxY = Math.min(bounds.offset_y + bounds.height - 1, Number(box.max_y) || bounds.offset_y + bounds.height - 1);
  const changes = [];
  const color = Number(target.color);
  for (let y = minY; y <= maxY && changes.length < maxChanges; y += 1) {
    for (let x = minX; x <= maxX && changes.length < maxChanges; x += 1) {
      const localIndex = (y - bounds.offset_y) * bounds.width + (x - bounds.offset_x);
      if (filled[localIndex] === -1 && cells[localIndex] === color) {
        changes.push({ index: y * Number(template.width) + x, color });
      }
    }
  }
  return changes;
}

/**
 * Server-derived local spatial effect. The client supplies intent only: a
 * center and optional radius. The server clamps the center to the special's
 * neighbourhood, reads only affected tiles, filters exact target colors and
 * never returns more than the existing 32-cell derived-change cap.
 */
export async function deriveBombChanges(db, {
  userId,
  template,
  special,
  centerX = null,
  centerY = null,
  radius = 3,
  maxChanges = SPECIAL_MAX_DERIVED_CHANGES,
} = {}) {
  const width = Number(template.width);
  const height = Number(template.height);
  const tileSize = Number(template.tile_size || DEFAULT_TILE_SIZE);
  const specialX = Number(special?.cell_index) % width;
  const specialY = Math.floor(Number(special?.cell_index) / width);
  const requestedX = Number.isFinite(Number(centerX)) ? Math.round(Number(centerX)) : specialX;
  const requestedY = Number.isFinite(Number(centerY)) ? Math.round(Number(centerY)) : specialY;
  const x = Math.max(0, Math.min(width - 1, requestedX));
  const y = Math.max(0, Math.min(height - 1, requestedY));
  if (Math.hypot(x - specialX, y - specialY) > 6) return [];
  const safeRadius = Math.max(1, Math.min(4, Math.floor(Number(radius) || 3)));
  const minX = Math.max(0, x - safeRadius);
  const maxX = Math.min(width - 1, x + safeRadius);
  const minY = Math.max(0, y - safeRadius);
  const maxY = Math.min(height - 1, y + safeRadius);
  const tileKeys = new Set();
  for (let candidateY = minY; candidateY <= maxY; candidateY += 1) {
    for (let candidateX = minX; candidateX <= maxX; candidateX += 1) {
      if (Math.hypot(candidateX - x, candidateY - y) > safeRadius) continue;
      tileKeys.add(`${Math.floor(candidateX / tileSize)}:${Math.floor(candidateY / tileSize)}`);
    }
  }
  const tileState = new Map();
  for (const key of tileKeys) {
    const [tileX, tileY] = key.split(':').map(Number);
    const bounds = getTileBounds({ width, height, tileSize, tileX, tileY });
    const row = await db.get(
      'SELECT cells_json FROM coloring_template_tiles WHERE template_id=? AND tile_x=? AND tile_y=?',
      [template.id, bounds.tile_x, bounds.tile_y],
    );
    if (!row) continue;
    const progress = await db.get(
      'SELECT filled_json FROM coloring_tiled_progress_tiles WHERE user_id=? AND template_id=? AND tile_x=? AND tile_y=?',
      [userId, template.id, bounds.tile_x, bounds.tile_y],
    );
    tileState.set(key, {
      bounds,
      cells: parseJsonArray(row.cells_json) || [],
      filled: parseJsonArray(progress?.filled_json) || Array(bounds.cell_count).fill(-1),
    });
  }
  const changes = [];
  for (let candidateY = minY; candidateY <= maxY && changes.length < maxChanges; candidateY += 1) {
    for (let candidateX = minX; candidateX <= maxX && changes.length < maxChanges; candidateX += 1) {
      if (Math.hypot(candidateX - x, candidateY - y) > safeRadius) continue;
      const tileX = Math.floor(candidateX / tileSize);
      const tileY = Math.floor(candidateY / tileSize);
      const state = tileState.get(`${tileX}:${tileY}`);
      if (!state) continue;
      const localX = candidateX - state.bounds.offset_x;
      const localY = candidateY - state.bounds.offset_y;
      const localIndex = localY * state.bounds.width + localX;
      const color = state.cells[localIndex];
      if (state.filled[localIndex] === -1 && Number.isInteger(color)) {
        changes.push({ index: candidateY * width + candidateX, color });
      }
    }
  }
  return changes;
}

/**
 * Server-derived Fuse chain. The claimed marker is painted in the claim
 * action, so the resolution never removes progress: it only returns exact
 * correct cells from the fuse marker's local window and at most three
 * bounded chain steps. Disarm uses the same derivation and consumes the offer.
 */
export function deriveFuseChanges({
  cells,
  filled,
  width,
  height,
  specialIndex,
  maxSteps = FUSE_CHAIN_MAX_STEPS,
  cellsPerStep = FUSE_CHAIN_CELLS,
} = {}) {
  const parsedCells = Array.isArray(cells) ? cells : (parseJsonArray(cells) || []);
  const parsedFilled = Array.isArray(filled) ? filled : (parseJsonArray(filled) || []);
  const safeWidth = Number(width);
  const safeHeight = Number(height);
  const anchorIndex = Number(specialIndex);
  const anchorX = anchorIndex % safeWidth;
  const anchorY = Math.floor(anchorIndex / safeWidth);
  const changes = [];
  const seen = new Set([anchorIndex]);
  for (let step = 0; step < maxSteps && changes.length < SPECIAL_MAX_DERIVED_CHANGES; step += 1) {
    const offset = step + 1;
    const candidates = [];
    for (let candidateY = Math.max(0, anchorY - offset); candidateY <= Math.min(safeHeight - 1, anchorY + offset); candidateY += 1) {
      for (let candidateX = Math.max(0, anchorX - offset); candidateX <= Math.min(safeWidth - 1, anchorX + offset); candidateX += 1) {
        const index = candidateY * safeWidth + candidateX;
        const color = Number(parsedCells[index]);
        if (parsedFilled[index] === -1 && Number.isInteger(color)) {
          candidates.push({ index, color, distance: Math.max(Math.abs(candidateX - anchorX), Math.abs(candidateY - anchorY)) });
        }
      }
    }
    candidates.sort((first, second) => first.distance - second.distance || first.index - second.index);
    for (const candidate of candidates) {
      if (changes.length >= cellsPerStep * (step + 1) || changes.length >= SPECIAL_MAX_DERIVED_CHANGES) break;
      if (seen.has(candidate.index)) continue;
      seen.add(candidate.index);
      changes.push({ index: candidate.index, color: candidate.color, distance: candidate.distance });
    }
  }
  return changes;
}

/** Tiled variant: read the few tiles around the fuse marker and derive exact correct cells. */
export async function deriveTiledFuseChanges(db, {
  userId,
  template,
  special,
  maxChanges = SPECIAL_MAX_DERIVED_CHANGES,
  excludeFilled = true,
} = {}) {
  const width = Number(template.width);
  const height = Number(template.height);
  const tileSize = Number(template.tile_size || DEFAULT_TILE_SIZE);
  const anchorIndex = Number(special?.cell_index);
  const anchorX = anchorIndex % width;
  const anchorY = Math.floor(anchorIndex / width);
  const minX = Math.max(0, anchorX - FUSE_CHAIN_MAX_STEPS);
  const minY = Math.max(0, anchorY - FUSE_CHAIN_MAX_STEPS);
  const maxX = Math.min(width - 1, anchorX + FUSE_CHAIN_MAX_STEPS);
  const maxY = Math.min(height - 1, anchorY + FUSE_CHAIN_MAX_STEPS);
  const tileKeys = new Set();
  for (let candidateY = minY; candidateY <= maxY; candidateY += 1) {
    for (let candidateX = minX; candidateX <= maxX; candidateX += 1) {
      tileKeys.add(`${Math.floor(candidateX / tileSize)}:${Math.floor(candidateY / tileSize)}`);
    }
  }
  const tileState = new Map();
  for (const key of tileKeys) {
    const [tileX, tileY] = key.split(':').map(Number);
    const bounds = getTileBounds({ width, height, tileSize, tileX, tileY });
    const row = await db.get(
      'SELECT cells_json FROM coloring_template_tiles WHERE template_id=? AND tile_x=? AND tile_y=?',
      [template.id, bounds.tile_x, bounds.tile_y],
    );
    if (!row) continue;
    const progress = await db.get(
      'SELECT filled_json FROM coloring_tiled_progress_tiles WHERE user_id=? AND template_id=? AND tile_x=? AND tile_y=?',
      [userId, template.id, bounds.tile_x, bounds.tile_y],
    );
    tileState.set(key, {
      bounds,
      cells: parseJsonArray(row.cells_json) || [],
      filled: parseJsonArray(progress?.filled_json) || Array(bounds.cell_count).fill(-1),
    });
  }
  const changes = [];
  const seen = new Set([anchorIndex]);
  // Keep tiled transport byte-for-byte equivalent to deriveFuseChanges: the
  // server still reads only the small local tile window, but the chain is
  // built ring by ring in the canonical order rather than by a broad window
  // sort. This preserves one bounded, deterministic gameplay contract.
  for (let step = 0; step < FUSE_CHAIN_MAX_STEPS && changes.length < maxChanges; step += 1) {
    const offset = step + 1;
    const candidates = [];
    for (let candidateY = Math.max(0, anchorY - offset); candidateY <= Math.min(height - 1, anchorY + offset); candidateY += 1) {
      for (let candidateX = Math.max(0, anchorX - offset); candidateX <= Math.min(width - 1, anchorX + offset); candidateX += 1) {
        const candidateIndex = candidateY * width + candidateX;
        if (seen.has(candidateIndex)) continue;
        const tileX = Math.floor(candidateX / tileSize);
        const tileY = Math.floor(candidateY / tileSize);
        const state = tileState.get(`${tileX}:${tileY}`);
        if (!state) continue;
        const localX = candidateX - state.bounds.offset_x;
        const localY = candidateY - state.bounds.offset_y;
        const localIndex = localY * state.bounds.width + localX;
        const color = Number(state.cells[localIndex]);
        if ((!excludeFilled || state.filled[localIndex] === -1) && Number.isInteger(color)) {
          candidates.push({
            index: candidateIndex,
            color,
            distance: Math.max(Math.abs(candidateX - anchorX), Math.abs(candidateY - anchorY)),
          });
        }
      }
    }
    candidates.sort((first, second) => first.distance - second.distance || first.index - second.index);
    for (const candidate of candidates) {
      if (changes.length >= maxChanges || changes.length >= FUSE_CHAIN_CELLS * (step + 1)) break;
      seen.add(candidate.index);
      changes.push(candidate);
    }
  }
  return changes;
}

/**
 * One real Fuse chain step is one outward ring of the visible chain. Rings
 * with no remaining cells are omitted, so the offer always describes the
 * actions the player still has to take.
 */
export function buildFuseOfferSteps(derivedChanges, maxSteps = FUSE_CHAIN_MAX_STEPS) {
  const byDistance = new Map();
  for (const change of derivedChanges || []) {
    const distance = Math.max(1, Math.min(maxSteps, Number(change?.distance) || 1));
    const group = byDistance.get(distance) || [];
    group.push(change);
    byDistance.set(distance, group);
  }
  return [...byDistance.keys()]
    .sort((first, second) => first - second)
    .slice(0, maxSteps)
    .map((distance, index) => {
      const cells = byDistance.get(distance).length;
      return { step: index + 1, distance, cells, estimated_cells: cells };
    });
}

/** The next ring of remaining Fuse chain cells. */
export function takeFuseStepChanges(derivedChanges, maxSteps = FUSE_CHAIN_MAX_STEPS) {
  const remaining = Array.isArray(derivedChanges) ? derivedChanges : [];
  if (!remaining.length) return [];
  const nextDistance = Math.min(...remaining.map((change) => (
    Math.max(1, Math.min(maxSteps, Number(change?.distance) || 1))
  )));
  return remaining.filter((change) => (
    Math.max(1, Math.min(maxSteps, Number(change?.distance) || 1)) === nextDistance
  ));
}

/** The chain cells that remain after the next ring has been disarmed. */
export function remainingFuseStepChanges(derivedChanges, maxSteps = FUSE_CHAIN_MAX_STEPS) {
  const remaining = Array.isArray(derivedChanges) ? derivedChanges : [];
  if (!remaining.length) return [];
  const nextDistance = Math.min(...remaining.map((change) => (
    Math.max(1, Math.min(maxSteps, Number(change?.distance) || 1))
  )));
  return remaining.filter((change) => (
    Math.max(1, Math.min(maxSteps, Number(change?.distance) || 1)) > nextDistance
  ));
}

/**
 * The Fuse chain is fixed at claim time so repeated disarm steps stay inside
 * the event's 32-cell cap. The indexes ride in the existing offer response
 * journal, so no schema change is needed.
 */
export async function findStoredFuseChain(db, { userId, templateId, specialId, limit = SPARK_OFFER_RECOVERY_BATCH_LIMIT } = {}) {
  const batches = await db.all(
    `SELECT response_json
       FROM coloring_progress_batches
      WHERE user_id=? AND template_id=?
      ORDER BY created_at DESC, revision_after DESC
      LIMIT ?`,
    [userId, templateId, limit],
  );
  for (const batch of batches || []) {
    const offer = parseJsonObject(batch?.response_json)?.special_offer;
    if (!offer || String(offer.special_id || '') !== String(specialId) || offer.kind !== FUSE_KIND) continue;
    if (!Array.isArray(offer.chain_cells) || !offer.chain_cells.length) continue;
    const chain = offer.chain_cells
      .map((index) => Number(index))
      .filter((index) => Number.isInteger(index) && index >= 0);
    if (chain.length && chain.length <= SPECIAL_MAX_DERIVED_CHANGES) return chain;
  }
  return null;
}

/** Keep only the fixed claim-time chain cells that are still unfilled. */
export function remainingFuseChangesFromChain(derivedChanges, chain) {
  const chainSet = new Set((chain || []).map((index) => Number(index)));
  return (derivedChanges || []).filter((change) => chainSet.has(Number(change.index)));
}

/** Row-major twin of deriveBombChanges for legacy templates. */
export function deriveLegacyBombChanges({
  cells,
  filled,
  width,
  height,
  specialIndex,
  centerX = null,
  centerY = null,
  radius = 3,
  maxChanges = SPECIAL_MAX_DERIVED_CHANGES,
} = {}) {
  const parsedCells = Array.isArray(cells) ? cells : (parseJsonArray(cells) || []);
  const parsedFilled = Array.isArray(filled) ? filled : (parseJsonArray(filled) || []);
  const safeWidth = Number(width);
  const safeHeight = Number(height);
  const specialX = Number(specialIndex) % safeWidth;
  const specialY = Math.floor(Number(specialIndex) / safeWidth);
  const requestedX = Number.isFinite(Number(centerX)) ? Math.round(Number(centerX)) : specialX;
  const requestedY = Number.isFinite(Number(centerY)) ? Math.round(Number(centerY)) : specialY;
  const x = Math.max(0, Math.min(safeWidth - 1, requestedX));
  const y = Math.max(0, Math.min(safeHeight - 1, requestedY));
  if (Math.hypot(x - specialX, y - specialY) > 6) return [];
  const safeRadius = Math.max(1, Math.min(4, Math.floor(Number(radius) || 3)));
  const minX = Math.max(0, x - safeRadius);
  const maxX = Math.min(safeWidth - 1, x + safeRadius);
  const minY = Math.max(0, y - safeRadius);
  const maxY = Math.min(safeHeight - 1, y + safeRadius);
  const changes = [];
  for (let candidateY = minY; candidateY <= maxY && changes.length < maxChanges; candidateY += 1) {
    for (let candidateX = minX; candidateX <= maxX && changes.length < maxChanges; candidateX += 1) {
      if (Math.hypot(candidateX - x, candidateY - y) > safeRadius) continue;
      const index = candidateY * safeWidth + candidateX;
      const color = Number(parsedCells[index]);
      if (parsedFilled[index] === -1 && Number.isInteger(color)) {
        changes.push({ index, color });
      }
    }
  }
  return changes;
}

