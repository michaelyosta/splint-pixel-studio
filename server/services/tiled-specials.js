/**
 * Read-only recovery for the offer_token that was only ever returned by the
 * claim response and persisted inside coloring_progress_batches.response_json.
 * The scan is bounded, never rotates the token or mutates progress state, and
 * control users always get null.
 */
export async function findStoredSparkOffer(db, { userId, templateId } = {}) {
  if (getSparkExperimentGroup(userId, templateId) !== 'treatment') return null;
  const active = await db.get(
    `SELECT p.special_id, p.offer_revision, p.offer_token_hash, c.kind, c.cell_index
       FROM coloring_special_progress p
       JOIN coloring_special_cells c
         ON c.template_id=p.template_id AND c.special_id=p.special_id
      WHERE p.user_id=? AND p.template_id=? AND p.status='offered'
      ORDER BY p.updated_at DESC, p.special_id DESC
      LIMIT 1`,
    [userId, templateId],
  );
  if (!active) return null;
  const batches = await db.all(
    `SELECT response_json, revision_after, created_at
       FROM coloring_progress_batches
      WHERE user_id=? AND template_id=?
      ORDER BY created_at DESC, revision_after DESC
      LIMIT ?`,
    [userId, templateId, SPARK_OFFER_RECOVERY_BATCH_LIMIT],
  );
  for (const batch of batches || []) {
    const offer = parseJsonObject(batch?.response_json)?.special_offer;
    if (!offer || String(offer.special_id || '') !== String(active.special_id)) continue;
    if (typeof offer.offer_token !== 'string' || !offer.offer_token) continue;
    if (active.offer_token_hash && hashOfferToken(offer.offer_token) !== active.offer_token_hash) continue;
    if (active.offer_revision != null && offer.progress_revision != null
      && Number(offer.progress_revision) !== Number(active.offer_revision)) continue;
    const base = {
      special_id: String(offer.special_id),
      offer_token: offer.offer_token,
      progress_revision: Number(offer.progress_revision ?? active.offer_revision ?? batch.revision_after ?? 0),
    };
    if (active.kind === BOMB_KIND) {
      const template = await db.get('SELECT width FROM coloring_templates WHERE id=?', [templateId]);
      const width = Number(template?.width || 0);
      const bombIndex = Number(active.cell_index);
      return {
        ...base,
        kind: BOMB_KIND,
        radius: Number.isFinite(Number(offer.radius)) ? Number(offer.radius) : BOMB_RADIUS,
        center_x: width > 0 ? bombIndex % width : (Number.isFinite(Number(offer.center_x)) ? Number(offer.center_x) : null),
        center_y: width > 0 ? Math.floor(bombIndex / width) : (Number.isFinite(Number(offer.center_y)) ? Number(offer.center_y) : null),
      };
    }
    if (active.kind === FUSE_KIND) {
      if (!Array.isArray(offer.steps) || !offer.steps.length) continue;
      return {
        ...base,
        kind: FUSE_KIND,
        steps: offer.steps.slice(0, 3),
        disarm: true,
        chain_cells: Array.isArray(offer.chain_cells) ? offer.chain_cells.slice(0, SPECIAL_MAX_DERIVED_CHANGES) : [],
      };
    }
    if (active.kind === HAZARD_KIND) {
      return {
        ...base,
        kind: HAZARD_KIND,
        disarm: true,
        reward_cells: Number.isFinite(Number(offer.reward_cells)) ? Number(offer.reward_cells) : 0,
        reward_cap: Number.isFinite(Number(offer.reward_cap)) ? Number(offer.reward_cap) : 16,
        penalty: offer.penalty || { temporary: true, cells: 2, progress_deleted: 0 },
      };
    }
    if (active.kind === CHOICE_KIND) {
      if (!Array.isArray(offer.choice_options) || !offer.choice_options.length) continue;
      return {
        ...base,
        kind: CHOICE_KIND,
        choice_options: offer.choice_options.slice(0, 2),
      };
    }
    if (!Array.isArray(offer.target_options) || !offer.target_options.length) continue;
    const targetOptions = offer.target_options.slice(0, 2);
    const defaultOptionId = String(offer.default_option_id || targetOptions[0]?.option_id || '');
    return {
      ...base,
      kind: SPARK_KIND,
      target_options: targetOptions,
      default_option_id: defaultOptionId,
      auto_apply: offer.auto_apply !== false,
      interaction_cost: 0,
      target_effort: offer.target_effort
        || describeSpecialTargetEffort(targetOptions.find((option) => option.option_id === defaultOptionId)
          || targetOptions[0]),
    };
  }
  return null;
}

