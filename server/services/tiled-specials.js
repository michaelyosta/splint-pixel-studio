function specialDiagnosticsStorageMode(template) {
  if (template?.storage_mode) return String(template.storage_mode);
  if (Array.isArray(template?.cells)) return 'legacy';
  return 'tiled';
}

function specialDiagnosticsTotalCells(template, progress) {
  const fromProgress = Number(progress?.total_cells);
  if (Number.isFinite(fromProgress) && fromProgress > 0) return Math.floor(fromProgress);
  const fromTemplate = Number(template?.width) * Number(template?.height);
  if (Number.isFinite(fromTemplate) && fromTemplate > 0) return Math.floor(fromTemplate);
  if (Array.isArray(template?.cells)) return template.cells.length;
  return 0;
}

function specialDiagnosticsCompletedCells(template, progress) {
  const direct = Number(progress?.completed_cells);
  if (Number.isFinite(direct) && direct >= 0) return Math.floor(direct);
  const filled = Array.isArray(progress?.filled)
    ? progress.filled
    : parseJsonArray(progress?.filled_json);
  if (Array.isArray(template?.cells) && Array.isArray(filled)
    && template.cells.length === filled.length) {
    let count = 0;
    for (let index = 0; index < template.cells.length; index += 1) {
      if (filled[index] === template.cells[index]) count += 1;
    }
    return count;
  }
  return 0;
}

