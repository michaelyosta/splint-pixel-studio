function parseJsonArray(value) {
  if (Array.isArray(value)) return value;
  if (typeof value !== 'string') return null;
  try {
    const parsed = JSON.parse(value);
    return Array.isArray(parsed) ? parsed : null;
  } catch {
    return null;
  }
}

function parseJsonObject(value) {
  if (value && typeof value === 'object' && !Array.isArray(value)) return value;
  if (typeof value !== 'string') return null;
  try {
    const parsed = JSON.parse(value);
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : null;
  } catch {
    return null;
  }
}

function hashString(value) {
  return createHash('sha256').update(String(value)).digest();
}

function fnvHash(value) {
  let hash = 2166136261;
  for (const character of String(value)) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

export function specialDensityForGrid(width, height) {
  const totalCells = Number(width) * Number(height);
  // Tiny compatibility fixtures and short legacy-like tiled canvases keep a
  // single discoverable event. Larger maps move to event cadence rather than
  // percentage-of-map scarcity: short maps stay calm, medium maps need a
  // slightly denser route to keep p95 target gaps bounded, and 1200-class
  // maps use a capped 1/175 candidate tier after the early guarantee. The simulator
  // showed that 1/400 leaves a long-tail gap above the V1 target on large maps.
  if (totalCells <= 8_192) return Math.max(1, totalCells);
  if (totalCells <= 50_000) return SPECIAL_EVENT_DENSITY_CELLS.small;
  if (totalCells < 800_000) return SPECIAL_EVENT_DENSITY_CELLS.medium;
  return SPECIAL_EVENT_DENSITY_CELLS.large;
}

