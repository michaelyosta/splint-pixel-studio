function tileMap(tiles) {
  return new Map((tiles || []).map((tile) => [`${Number(tile.tile_x)}:${Number(tile.tile_y)}`, tile]));
}

function tileColorCounts(tile, paletteLength = Infinity) {
  const counts = new Map();
  for (const color of parseJsonArray(tile?.cells) || []) {
    if (!Number.isInteger(color) || color < 0 || color >= paletteLength) continue;
    counts.set(color, (counts.get(color) || 0) + 1);
  }
  return counts;
}

function dominantColor(tiles) {
  const totals = new Map();
  for (const tile of tiles || []) {
    for (const [color, count] of tileColorCounts(tile)) {
      totals.set(color, (totals.get(color) || 0) + count);
    }
  }
  return [...totals.entries()].sort((first, second) => second[1] - first[1] || first[0] - second[0])[0]?.[0] ?? 0;
}

function bestWindowForColor({ tile, bounds, color, cameraCenterX = 0, cameraCenterY = 0 }) {
  const cells = parseJsonArray(tile?.cells) || [];
  const width = bounds.width;
  const height = bounds.height;
  const candidates = [];
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      if (cells[y * width + x] !== color) continue;
      const minX = Math.max(0, x - 6);
      const minY = Math.max(0, y - 6);
      const maxX = Math.min(width - 1, minX + 11);
      const maxY = Math.min(height - 1, minY + 11);
      let count = 0;
      for (let windowY = minY; windowY <= maxY; windowY += 1) {
        for (let windowX = minX; windowX <= maxX; windowX += 1) {
          if (cells[windowY * width + windowX] === color) count += 1;
        }
      }
      const anchorX = bounds.offset_x + x;
      const anchorY = bounds.offset_y + y;
      candidates.push({
        count,
        x,
        y,
        minX,
        minY,
        maxX,
        maxY,
        distance: Math.hypot(anchorX - cameraCenterX, anchorY - cameraCenterY),
      });
    }
  }
  candidates.sort((first, second) => (
    second.count - first.count
    || first.distance - second.distance
    || first.y - second.y
    || first.x - second.x
  ));
  return candidates[0] || null;
}

function initialTargetCell({ width, height, tileSize, tiles, preferredColor = null }) {
  const byKey = tileMap(tiles);
  const color = Number.isInteger(preferredColor) ? preferredColor : dominantColor(tiles);
  const centerX = width / 2;
  const centerY = height / 2;
  const candidates = [];
  for (const tile of tiles || []) {
    const tileX = Number(tile.tile_x);
    const tileY = Number(tile.tile_y);
    const bounds = getTileBounds({ width, height, tileSize, tileX, tileY });
    const counts = tileColorCounts(tile);
    const remaining = counts.get(color) || 0;
    if (!remaining) continue;
    const distance = Math.hypot(tileX * tileSize + tileSize / 2 - centerX, tileY * tileSize + tileSize / 2 - centerY);
    candidates.push({ tile, bounds, tileX, tileY, remaining, distance });
  }
  candidates.sort((first, second) => (
    (-second.distance + Math.min(second.remaining, 512) * 0.05)
      - (-first.distance + Math.min(first.remaining, 512) * 0.05)
    || first.tileY - second.tileY
    || first.tileX - second.tileX
  ));
  const selected = candidates[0];
  if (!selected || !byKey.has(`${selected.tileX}:${selected.tileY}`)) return null;
  const window = bestWindowForColor({
    tile: selected.tile,
    bounds: selected.bounds,
    color,
    cameraCenterX: centerX,
    cameraCenterY: centerY,
  });
  if (!window) return null;
  const digest = hashString(`early:${selected.tileX}:${selected.tileY}:${window.minX}:${window.minY}`);
  const matching = [];
  for (let y = window.minY; y <= window.maxY; y += 1) {
    for (let x = window.minX; x <= window.maxX; x += 1) {
      if (parseJsonArray(selected.tile.cells)?.[y * selected.bounds.width + x] === color) matching.push({ x, y });
    }
  }
  if (!matching.length) return null;
  const picked = matching[digest.readUInt32BE(0) % matching.length];
  const localIndex = picked.y * selected.bounds.width + picked.x;
  return {
    tile: selected.tile,
    tileX: selected.tileX,
    tileY: selected.tileY,
    localIndex,
    cellIndex: (selected.bounds.offset_y + picked.y) * width + selected.bounds.offset_x + picked.x,
    color,
    bounds: {
      minX: selected.bounds.offset_x + window.minX,
      minY: selected.bounds.offset_y + window.minY,
      maxX: selected.bounds.offset_x + window.maxX,
      maxY: selected.bounds.offset_y + window.maxY,
    },
  };
}

function macroRegions(width, height) {
  const columns = Math.ceil(width / SPARK_MACRO_REGION_SIZE);
  const rows = Math.ceil(height / SPARK_MACRO_REGION_SIZE);
  return Array.from({ length: rows * columns }, (_, index) => {
    const x = index % columns;
    const y = Math.floor(index / columns);
    return {
      x,
      y,
      width: Math.min(SPARK_MACRO_REGION_SIZE, width - x * SPARK_MACRO_REGION_SIZE),
      height: Math.min(SPARK_MACRO_REGION_SIZE, height - y * SPARK_MACRO_REGION_SIZE),
    };
  });
}

function regionQuotas(total, regions, requiredRegion) {
  const quotas = regions.map(() => Math.floor(total / Math.max(1, regions.length)));
  let remainder = total - quotas.reduce((sum, value) => sum + value, 0);
  const order = regions
    .map((region, index) => ({ index, rank: fnvHash(`quota:${region.x}:${region.y}`) }))
    .sort((first, second) => first.rank - second.rank);
  while (remainder > 0) {
    quotas[order[remainder % order.length].index] += 1;
    remainder -= 1;
  }
  if (requiredRegion != null && quotas[requiredRegion] === 0) {
    const donor = quotas.findIndex((quota, index) => index !== requiredRegion && quota > 1);
    if (donor >= 0) {
      quotas[donor] -= 1;
      quotas[requiredRegion] += 1;
    } else {
      const fallback = quotas.findIndex((quota, index) => index !== requiredRegion && quota > 0);
      if (fallback >= 0) {
        quotas[fallback] -= 1;
        quotas[requiredRegion] += 1;
      }
    }
  }
  return quotas;
}

function candidateInRegion({ region, quota, seed, ordinal, occupied, width, tileSize, byKey }) {
  if (!quota) return [];
  const subColumns = Math.max(1, Math.ceil(Math.sqrt(quota * region.width / Math.max(1, region.height))));
  const subRows = Math.max(1, Math.ceil(quota / subColumns));
  const slots = Array.from({ length: subRows * subColumns }, (_, index) => index)
    .sort((first, second) => fnvHash(`${seed}:region:${region.x}:${region.y}:${first}`)
      - fnvHash(`${seed}:region:${region.x}:${region.y}:${second}`));
  const result = [];
  for (let index = 0; index < quota; index += 1) {
    const slot = slots[index];
    const slotX = slot % subColumns;
    const slotY = Math.floor(slot / subColumns);
    const minX = region.x * SPARK_MACRO_REGION_SIZE + Math.floor(slotX * region.width / subColumns);
    const maxX = region.x * SPARK_MACRO_REGION_SIZE + Math.min(region.width - 1, Math.floor((slotX + 1) * region.width / subColumns) - 1);
    const minY = region.y * SPARK_MACRO_REGION_SIZE + Math.floor(slotY * region.height / subRows);
    const maxY = region.y * SPARK_MACRO_REGION_SIZE + Math.min(region.height - 1, Math.floor((slotY + 1) * region.height / subRows) - 1);
    const digest = hashString(`${seed}:region:${region.x}:${region.y}:${ordinal}:${slot}`);
    let picked = null;
    const spanX = Math.max(1, maxX - minX + 1);
    const spanY = Math.max(1, maxY - minY + 1);
    for (let attempt = 0; attempt < spanX * spanY; attempt += 1) {
      const offset = (digest.readUInt32BE(0) + attempt) % (spanX * spanY);
      const x = minX + (offset % spanX);
      const y = minY + Math.floor(offset / spanX);
      const cellIndex = y * width + x;
      const tileX = Math.floor(x / tileSize);
      const tileY = Math.floor(y / tileSize);
      if (!byKey.has(`${tileX}:${tileY}`) || occupied.has(cellIndex)) continue;
      picked = { x, y, cellIndex, tileX, tileY };
      break;
    }
    if (picked) {
      occupied.add(picked.cellIndex);
      result.push(picked);
    }
  }
  return result;
}

/**
 * Deterministic, sparse placement. Generation runs during template creation,
 * where the validated tile payload is already available; gameplay never
 * scans or regenerates the 1200x1200 grid.
 */
export function generateSparkCells({
  templateId,
  seed = templateId,
  width,
  height,
  tileSize = 32,
  tiles,
  earlyColor = null,
  densityCells = SPARK_DENSITY_CELLS,
  maxSpecials = SPARK_MAX_CELLS,
} = {}) {
  const grid = getTileGrid(width, height, tileSize);
  const orderedTiles = [...(tiles || [])]
    .filter((tile) => Array.isArray(parseJsonArray(tile.cells)))
    .sort((a, b) => Number(a.tile_y) - Number(b.tile_y) || Number(a.tile_x) - Number(b.tile_x));
  if (!orderedTiles.length) return [];
  const generationSeed = `${seed}:${grid.width}:${grid.height}:${SPECIAL_GENERATION_VERSION}`;
  const count = Math.min(
    Math.max(1, Number(maxSpecials) || SPARK_MAX_CELLS),
    Math.max(1, Math.ceil(grid.totalCells / Math.max(1, Number(densityCells) || SPARK_DENSITY_CELLS))),
  );
  const byKey = tileMap(orderedTiles);
  const occupied = new Set();
  const early = initialTargetCell({
    width: grid.width,
    height: grid.height,
    tileSize: grid.tile_size,
    tiles: orderedTiles,
    preferredColor: earlyColor,
  });
  const regions = macroRegions(grid.width, grid.height);
  const macroColumns = Math.ceil(grid.width / SPARK_MACRO_REGION_SIZE);
  const earlyRegion = early
    ? Math.floor(Math.floor(early.cellIndex / grid.width) / SPARK_MACRO_REGION_SIZE) * macroColumns
      + Math.floor((early.cellIndex % grid.width) / SPARK_MACRO_REGION_SIZE)
    : null;
  const quotas = regionQuotas(count, regions, earlyRegion);
  const result = [];
  if (early) {
    occupied.add(early.cellIndex);
    result.push({
      special_id: `sc_early_${hashString(`${generationSeed}:${early.cellIndex}`).toString('hex').slice(0, 16)}`,
      kind: SPARK_KIND,
      cell_index: early.cellIndex,
      tile_x: early.tileX,
      tile_y: early.tileY,
      local_index: early.localIndex,
      generation_version: SPECIAL_GENERATION_VERSION,
    });
    quotas[earlyRegion] = Math.max(0, quotas[earlyRegion] - 1);
  }
  for (let regionIndex = 0; regionIndex < regions.length && result.length < count; regionIndex += 1) {
    const region = regions[regionIndex];
    const candidates = candidateInRegion({
      region,
      quota: quotas[regionIndex],
      seed: generationSeed,
      ordinal: regionIndex,
      occupied,
      width: grid.width,
      tileSize: grid.tile_size,
      byKey,
    });
    for (const candidate of candidates) {
      if (result.length >= count) break;
      const tile = byKey.get(`${candidate.tileX}:${candidate.tileY}`);
      const bounds = getTileBounds({
        width: grid.width,
        height: grid.height,
        tileSize: grid.tile_size,
        tileX: candidate.tileX,
        tileY: candidate.tileY,
      });
      const localIndex = (candidate.y - bounds.offset_y) * bounds.width + candidate.x - bounds.offset_x;
      result.push({
        special_id: `sc_${hashString(`${generationSeed}:${candidate.cellIndex}`).toString('hex').slice(0, 16)}`,
        kind: SPARK_KIND,
        cell_index: candidate.cellIndex,
        tile_x: bounds.tile_x,
        tile_y: bounds.tile_y,
        local_index: localIndex,
        generation_version: SPECIAL_GENERATION_VERSION,
        color: parseJsonArray(tile.cells)?.[localIndex] ?? null,
      });
    }
  }
  return result.map(({ color: _color, ...cell }) => cell);
}

/**
 * The first placement contract remains Spark-compatible. New templates can
 * opt into a deterministic, bounded event mix without introducing a second
 * coordinate generator. The first/early candidate is always Spark so the
 * existing INITIAL_TARGET proof and the 28x28 compatibility fixture remain
 * valid. Existing persisted v2 rows are deliberately not rewritten here.
 */
function generationKindPattern() {
  return process.env.NODE_ENV === 'test'
    && process.env.SPECIAL_CELLS_LEGACY_CHOICE_FIXTURE === 'true'
    ? LEGACY_CHOICE_KIND_PATTERN
    : SPECIAL_KIND_PATTERN;
}

function applySpecialKindMix(cells, generationSeed) {
  const kindPattern = generationKindPattern();
  const cycleOffset = fnvHash(`${generationSeed}:weighted-cycle`) % kindPattern.length;
  return cells.map((cell, index) => {
    let kind = SPARK_KIND;
    if (index >= 1 && index <= 3) {
      kind = [SPARK_KIND, BOMB_KIND, SPARK_KIND][index - 1];
    } else if (index > 3) {
      kind = kindPattern[(index - 4 + cycleOffset) % kindPattern.length];
    }
    if (kind === HAZARD_KIND) {
      // Hazard is not part of the historical kind cycle. Fall back to Spark
      // here so the default mixed cadence stays exactly as shipped; hazard
      // placement is handled by the hazard generator when enabled.
      kind = SPARK_KIND;
    }
    return {
      ...cell,
      kind,
      generation_version: SPECIAL_GAMEPLAY_GENERATION_VERSION,
      kind_meta: normalizeSpecialKind(kind),
    };
  });
}

export function generateSpecialCells({ templateId, seed = templateId, width, height, tileSize = 32, tiles, earlyColor = null } = {}) {
  const sparks = generateSparkCells({
    templateId,
    seed,
    width,
    height,
    tileSize,
    tiles,
    earlyColor,
    densityCells: specialDensityForGrid(width, height),
    maxSpecials: SPECIAL_EVENT_MAX_CELLS,
  });
  const boundedSparks = capSpecialsPerTile(sparks);
  if (!boundedSparks.length) return [];
  const generationSeed = `${seed}:${width}:${height}:${SPECIAL_GAMEPLAY_GENERATION_VERSION}`;
  // A seeded cycle keeps the non-early mix deterministic. Choice remains an
  // accepted persisted kind, but is absent from new production generation.
  const mixed = applySpecialKindMix(boundedSparks, generationSeed);
  // Hazard is placed separately by the hazard generator; mixing it into the
  // shared cell set would collide with the hazard fixture at the same cell.
  return mixed.filter((cell) => cell.kind !== HAZARD_KIND);
}

/**
 * Legacy templates keep their canonical row-major cells, but use the same
 * placement contract. A single virtual tile keeps the persisted metadata
 * compatible with the tiled special-cell table without adding a second
 * special-cell model.
 */
export function generateLegacySparkCells({ templateId, seed = templateId, width, height, cells } = {}) {
  const safeWidth = Number(width);
  const safeHeight = Number(height);
  const parsedCells = parseJsonArray(cells) || [];
  const counts = new Map();
  for (const color of parsedCells) {
    if (Number.isInteger(color) && color >= 0) counts.set(color, (counts.get(color) || 0) + 1);
  }
  // The legacy player starts with findRewardingColor(), i.e. the smallest
  // remaining non-empty color. Feed that existing routing decision into the
  // shared placement generator so its early guarantee also applies to legacy.
  const earlyColor = [...counts.entries()]
    .sort((first, second) => first[1] - second[1] || first[0] - second[0])[0]?.[0] ?? null;
  const tileSize = Math.min(DEFAULT_TILE_SIZE, Math.max(safeWidth, safeHeight));
  const tiles = [];
  for (let tileY = 0; tileY < Math.ceil(safeHeight / tileSize); tileY += 1) {
    for (let tileX = 0; tileX < Math.ceil(safeWidth / tileSize); tileX += 1) {
      const bounds = getTileBounds({ width: safeWidth, height: safeHeight, tileSize, tileX, tileY });
      const tileCells = [];
      for (let y = 0; y < bounds.height; y += 1) {
        const rowStart = (bounds.offset_y + y) * safeWidth + bounds.offset_x;
        tileCells.push(...parsedCells.slice(rowStart, rowStart + bounds.width));
      }
      tiles.push({ tile_x: tileX, tile_y: tileY, cells: tileCells });
    }
  }
  const generated = generateSparkCells({
    templateId,
    seed,
    width: safeWidth,
    height: safeHeight,
    tileSize,
    tiles,
    earlyColor,
    densityCells: specialDensityForGrid(safeWidth, safeHeight),
    maxSpecials: SPECIAL_EVENT_MAX_CELLS,
  });
  // Preserve the exact v2 28x28 compatibility fixture. Larger legacy maps
  // use the same deterministic kind mix and tiered density as tiled while
  // retaining the legacy row-major transport.
  if (safeWidth * safeHeight <= SPECIAL_EVENT_MAX_CELLS) return generated;
  return applySpecialKindMix(generated, `${seed}:${safeWidth}:${safeHeight}:${SPECIAL_GAMEPLAY_GENERATION_VERSION}`);
}

function targetWindowForCells({ cells, filled, width, height, color, anchorIndex, windowSize = 12 }) {
  const anchorX = anchorIndex % width;
  const anchorY = Math.floor(anchorIndex / width);
  const minX = Math.max(0, Math.min(width - windowSize, anchorX - Math.floor(windowSize / 2)));
  const minY = Math.max(0, Math.min(height - windowSize, anchorY - Math.floor(windowSize / 2)));
  const maxX = Math.min(width - 1, minX + windowSize - 1);
  const maxY = Math.min(height - 1, minY + windowSize - 1);
  let estimatedCells = 0;
  for (let y = minY; y <= maxY; y += 1) {
    for (let x = minX; x <= maxX; x += 1) {
      const index = y * width + x;
      if (filled[index] === -1 && cells[index] === color) estimatedCells += 1;
    }
  }
  return {
    tile_x: 0,
    tile_y: 0,
    color,
    anchor_x: anchorX,
    anchor_y: anchorY,
    bounds: { min_x: minX, min_y: minY, max_x: maxX, max_y: maxY, width: maxX - minX + 1, height: maxY - minY + 1 },
    estimated_cells: estimatedCells,
  };
}

export function buildLegacySpecialTriggerEffort({
  cells, filled, width, height, specialIndex,
} = {}) {
  const index = Number(specialIndex);
  const color = Number(cells?.[index]);
  if (!Number.isInteger(index) || index < 0 || index >= Number(width) * Number(height)
    || !Number.isInteger(color)) {
    return describeSpecialTargetEffort(null);
  }
  return describeSpecialTargetEffort(targetWindowForCells({
    cells,
    filled,
    width,
    height,
    color,
    anchorIndex: index,
  }));
}

/** Same bounded two-option shape used by tiled Smart Engine special targets. */
export function buildLegacySparkTargetOptions({ cells, filled, width, height, specialIndex, maxOptions = 2 } = {}) {
  const targets = [];
  const colors = new Map();
  for (let index = 0; index < cells.length; index += 1) {
    if (filled[index] !== -1) continue;
    const color = Number(cells[index]);
    if (!Number.isInteger(color)) continue;
    colors.set(color, (colors.get(color) || 0) + 1);
  }
  for (const [color, remaining] of colors) {
    if (!remaining) continue;
    const anchors = [];
    for (let index = 0; index < cells.length; index += 1) {
      if (filled[index] === -1 && Number(cells[index]) === color) {
        anchors.push(targetWindowForCells({ cells, filled, width, height, color, anchorIndex: index }));
      }
    }
    anchors.sort((first, second) => second.estimated_cells - first.estimated_cells
      || Math.abs(first.anchor_x - (specialIndex % width)) - Math.abs(second.anchor_x - (specialIndex % width))
      || first.anchor_y - second.anchor_y || first.anchor_x - second.anchor_x);
    const best = anchors[0];
    if (isSpecialTargetEligible(best)) targets.push(best);
  }
  if (!targets.length) return [];
  targets.sort((first, second) => second.estimated_cells - first.estimated_cells
    || first.color - second.color);
  const first = targets[0];
  const second = targets.find((target) => target.color !== first.color) || targetWindowForCells({
    cells,
    filled,
    width,
    height,
    color: first.color,
    anchorIndex: Math.min(cells.length - 1, (specialIndex + Math.floor(cells.length / 2)) % cells.length),
  });
  return [first, second].filter(isSpecialTargetEligible).slice(0, maxOptions)
    .map((target, index) => ({ ...target, option_id: index === 0 ? 'a' : 'b' }));
}

export function deriveLegacySparkChanges({ cells, filled, width, height, target, maxChanges = SPARK_TARGET_MAX_CELLS } = {}) {
  const box = target?.bounds || {};
  const minX = Math.max(0, Number(box.min_x) || 0);
  const minY = Math.max(0, Number(box.min_y) || 0);
  const maxX = Math.min(width - 1, Number(box.max_x) || width - 1);
  const maxY = Math.min(height - 1, Number(box.max_y) || height - 1);
  const color = Number(target?.color);
  const changes = [];
  for (let y = minY; y <= maxY && changes.length < maxChanges; y += 1) {
    for (let x = minX; x <= maxX && changes.length < maxChanges; x += 1) {
      const index = y * width + x;
      if (filled[index] === -1 && cells[index] === color) changes.push({ index, color });
    }
  }
  return changes;
}

function sparkDistance(first, second, width) {
  const firstX = first.cell_index % width;
  const firstY = Math.floor(first.cell_index / width);
  const secondX = second.cell_index % width;
  const secondY = Math.floor(second.cell_index / width);
  return Math.hypot(firstX - secondX, firstY - secondY);
}

function initialRouteTarget({ width, height, tileSize, tile, color }) {
  const bounds = getTileBounds({ width, height, tileSize, tileX: Number(tile.tile_x), tileY: Number(tile.tile_y) });
  const window = bestWindowForColor({
    tile,
    bounds,
    color,
    cameraCenterX: width / 2,
    cameraCenterY: height / 2,
  });
  if (!window) return null;
  return {
    tile_x: Number(tile.tile_x),
    tile_y: Number(tile.tile_y),
    min_x: bounds.offset_x + window.minX,
    min_y: bounds.offset_y + window.minY,
    max_x: bounds.offset_x + window.maxX,
    max_y: bounds.offset_y + window.maxY,
  };
}

export function diagnoseSparkPlacement({ templateId, seed = templateId, width, height, tileSize = 32, tiles } = {}) {
  const grid = getTileGrid(width, height, tileSize);
  const generated = generateSparkCells({ templateId, seed, width, height, tileSize, tiles });
  const regions = macroRegions(grid.width, grid.height);
  const macroCounts = regions.map((region) => ({
    region_x: region.x,
    region_y: region.y,
    count: generated.filter((cell) => (
      Math.floor((cell.cell_index % grid.width) / SPARK_MACRO_REGION_SIZE) === region.x
      && Math.floor(Math.floor(cell.cell_index / grid.width) / SPARK_MACRO_REGION_SIZE) === region.y
    )).length,
  }));
  const byKey = tileMap(tiles);
  const colors = {};
  for (const cell of generated) {
    const tile = byKey.get(`${cell.tile_x}:${cell.tile_y}`);
    const color = parseJsonArray(tile?.cells)?.[cell.local_index];
    colors[color] = (colors[color] || 0) + 1;
  }
  const distances = [];
  for (let index = 1; index < generated.length; index += 1) {
    let nearest = Infinity;
    for (let previous = 0; previous < index; previous += 1) {
      nearest = Math.min(nearest, sparkDistance(generated[index], generated[previous], grid.width));
    }
    distances.push(nearest);
  }
  const orderedTiles = [...(tiles || [])].sort((a, b) => Number(a.tile_y) - Number(b.tile_y) || Number(a.tile_x) - Number(b.tile_x));
  const color = dominantColor(orderedTiles);
  const centerX = grid.width / 2;
  const centerY = grid.height / 2;
  const ranked = orderedTiles.map((tile) => {
    const count = tileColorCounts(tile).get(color) || 0;
    const distance = Math.hypot(Number(tile.tile_x) * grid.tile_size + grid.tile_size / 2 - centerX,
      Number(tile.tile_y) * grid.tile_size + grid.tile_size / 2 - centerY);
    return { tile, count, score: -distance + Math.min(count, 512) * 0.05 };
  }).filter((entry) => entry.count > 0)
    .sort((first, second) => second.score - first.score || Number(first.tile.tile_y) - Number(second.tile.tile_y)
      || Number(first.tile.tile_x) - Number(second.tile.tile_x));
  let firstSparkTarget = null;
  for (let index = 0; index < ranked.length; index += 1) {
    const target = initialRouteTarget({ width: grid.width, height: grid.height, tileSize: grid.tile_size, tile: ranked[index].tile, color });
    if (!target) continue;
    if (generated.some((cell) => cell.cell_index % grid.width >= target.min_x
      && cell.cell_index % grid.width <= target.max_x
      && Math.floor(cell.cell_index / grid.width) >= target.min_y
      && Math.floor(cell.cell_index / grid.width) <= target.max_y
      && byKey.get(`${cell.tile_x}:${cell.tile_y}`))) {
      firstSparkTarget = index + 1;
      break;
    }
  }
  const targetCount = generated.length ? firstSparkTarget : null;
  return {
    template_id: templateId,
    seed,
    total_cells: grid.totalCells,
    spark_count: generated.length,
    density_cells_per_spark: generated.length ? grid.totalCells / generated.length : null,
    macro_region_size: SPARK_MACRO_REGION_SIZE,
    macro_region_columns: Math.ceil(grid.width / SPARK_MACRO_REGION_SIZE),
    macro_region_rows: Math.ceil(grid.height / SPARK_MACRO_REGION_SIZE),
    spark_count_by_macro_region: macroCounts,
    spark_count_by_color: colors,
    nearest_neighbor_distance: {
      min: distances.length ? Math.min(...distances) : null,
      average: distances.length ? distances.reduce((sum, value) => sum + value, 0) / distances.length : null,
      max: distances.length ? Math.max(...distances) : null,
    },
    smart_engine: {
      dominant_color: color,
      expected_targets_to_first_spark: targetCount,
      worst_case_early_route_without_spark: targetCount == null ? ranked.length : Math.max(0, targetCount - 1),
      early_target_guaranteed: targetCount === 1,
    },
  };
}

