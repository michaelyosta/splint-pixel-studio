export function specialEffortBin(value) {
  const cells = Math.max(0, Math.floor(Number(value) || 0));
  if (cells <= 0) return null;
  if (cells === 1) return '1';
  if (cells <= 3) return '2-3';
  if (cells <= 12) return '4-12';
  if (cells <= 32) return '13-32';
  if (cells <= 50) return '33-50';
  if (cells <= 200) return '51-200';
  return '200+';
}

export function isSpecialTargetEligible(targetOrCells) {
  const cells = typeof targetOrCells === 'object'
    ? Number(targetOrCells?.estimated_cells)
    : Number(targetOrCells);
  return Number.isFinite(cells) && cells >= SPECIAL_MIN_EFFECT_CELLS;
}

export function describeSpecialTargetEffort(target) {
  const estimatedCells = Math.max(0, Math.floor(Number(target?.estimated_cells) || 0));
  const width = Math.max(0, Math.floor(Number(target?.bounds?.width) || 0));
  const height = Math.max(0, Math.floor(Number(target?.bounds?.height) || 0));
  const boundsArea = width * height;
  return {
    estimated_cells: estimatedCells,
    effort_bin: specialEffortBin(estimatedCells),
    bounds_area: boundsArea,
    target_density: boundsArea > 0 ? estimatedCells / boundsArea : null,
    eligible: isSpecialTargetEligible(estimatedCells),
  };
}

function effortPercentile(values, percentile) {
  if (!values.length) return null;
  const sorted = [...values].sort((first, second) => first - second);
  const index = Math.min(sorted.length - 1,
    Math.max(0, Math.ceil((percentile / 100) * sorted.length) - 1));
  return sorted[index];
}

export function summarizeSpecialEffort(values = []) {
  const normalized = values
    .map((value) => Math.max(0, Math.floor(Number(value) || 0)))
    .filter((value) => value > 0);
  const bins = Object.fromEntries(SPECIAL_EFFORT_BIN_KEYS.map((key) => [key, 0]));
  for (const value of normalized) bins[specialEffortBin(value)] += 1;
  return {
    sample_count: normalized.length,
    bins,
    min: normalized.length ? Math.min(...normalized) : null,
    p50: effortPercentile(normalized, 50),
    p90: effortPercentile(normalized, 90),
    p95: effortPercentile(normalized, 95),
    max: normalized.length ? Math.max(...normalized) : null,
  };
}

/**
 * Generation must enforce the same per-tile bound as the tile payload. A
 * database-only marker is not discoverable if readTileSpecials truncates it.
 */
export function capSpecialsPerTile(cells, limit = SPECIAL_TILE_METADATA_LIMIT) {
  const counts = new Map();
  const result = [];
  for (const cell of cells || []) {
    const key = `${Number(cell.tile_x)}:${Number(cell.tile_y)}`;
    const count = counts.get(key) || 0;
    if (count >= limit) continue;
    counts.set(key, count + 1);
    result.push(cell);
  }
  return result;
}

