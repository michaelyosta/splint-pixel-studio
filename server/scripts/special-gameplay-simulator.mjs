/**
 * Deterministic synthetic artwork: seeded Voronoi regions over a fixed
 * palette. The palette is stable per size; only the Spark seed changes across
 * baseline runs.
 */
export function buildSyntheticTemplate({
  width,
  height,
  tileSize = DEFAULT_TILE_SIZE,
  paletteSize = DEFAULT_PALETTE_SIZE,
  seed = 'synthetic-artwork-v1',
} = {}) {
  const grid = getTileGrid(width, height, tileSize);
  const rng = mulberry32(fnv1a(`${seed}:${grid.width}:${grid.height}:${paletteSize}`));
  const centers = [];
  for (let index = 0; index < paletteSize; index += 1) {
    centers.push({
      x: Math.floor(rng() * grid.width),
      y: Math.floor(rng() * grid.height),
      color: index,
    });
  }
  const tiles = [];
  for (let tileY = 0; tileY < grid.tiles_y; tileY += 1) {
    for (let tileX = 0; tileX < grid.tiles_x; tileX += 1) {
      const bounds = getTileBounds({
        width: grid.width,
        height: grid.height,
        tileSize: grid.tile_size,
        tileX,
        tileY,
      });
      const cells = new Array(bounds.cell_count);
      for (let y = 0; y < bounds.height; y += 1) {
        for (let x = 0; x < bounds.width; x += 1) {
          const gx = bounds.offset_x + x;
          const gy = bounds.offset_y + y;
          let bestColor = 0;
          let bestDistance = Infinity;
          for (const center of centers) {
            const dx = gx - center.x;
            const dy = gy - center.y;
            const distance = dx * dx + dy * dy;
            if (distance < bestDistance) {
              bestDistance = distance;
              bestColor = center.color;
            }
          }
          cells[y * bounds.width + x] = bestColor;
        }
      }
      tiles.push({ tile_x: tileX, tile_y: tileY, cells });
    }
  }
  const palette = Array.from({ length: paletteSize }, (_, index) => `#sim${index}`);
  return {
    template: {
      id: `synthetic-${grid.width}x${grid.height}`,
      width: grid.width,
      height: grid.height,
      tile_size: grid.tile_size,
      palette,
    },
    tiles,
  };
}

