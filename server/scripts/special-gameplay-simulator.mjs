/**
 * Baseline special-gameplay simulator. The default remains Spark-only; an
 * opt-in event mix labels the same deterministic candidates with the
 * production multi-kind cycle for cadence and balance analysis.
 *
 * This module reuses the production placement and guidance contracts
 * (density, pity interval, derived-change cap) but runs them in memory
 * against synthetic deterministic artwork. It deliberately models a simple
 * autopilot: the player always follows the smart route and always uses the
 * first available effect resolution. Human behavior, manual color changes, free
 * exploration, and network latency are outside this baseline.
 *
 * ROUTE MODEL: APPROXIMATION
 * The production planner reads compact counts and at most one real tile; the
 * simulator reproduces those selection rules at tile granularity without a
 * database. Window scoring is byte-for-byte equivalent to
 * chooseActionableWindow, but travel, user choice, and skipped offers are
 * not modeled. This is a baseline, not a final event mix.
 */

