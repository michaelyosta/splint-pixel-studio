/*
 * Parameterized reproduction of the production Spark placement contract.
 * server/services/tiled-specials.js is fixed to the shipped density and
 * max-cell constants, so the cadence sweep threads the same deterministic
 * algorithm here with sweep parameters. With default constants the generated
 * cells and diagnostics are byte-for-byte identical to the service functions.
 */
function placementHashString(value) {
  return createHash('sha256').update(String(value)).digest();
}

function placementFnvHash(value) {
  let hash = 2166136261;
  for (const character of String(value)) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function placementTileMap(tiles) {
  return new Map((tiles || []).map((tile) => [`${Number(tile.tile_x)}:${Number(tile.tile_y)}`, tile]));
}

function placementTileColorCounts(tile, paletteLength = Infinity) {
  const counts = new Map();
  for (const color of Array.isArray(tile?.cells) ? tile.cells : []) {
    if (!Number.isInteger(color) || color < 0 || color >= paletteLength) continue;
    counts.set(color, (counts.get(color) || 0) + 1);
  }
  return counts;
}

function placementDominantColor(tiles) {
  const totals = new Map();
  for (const tile of tiles || []) {
    for (const [color, count] of placementTileColorCounts(tile)) {
      totals.set(color, (totals.get(color) || 0) + count);
    }
  }
  return [...totals.entries()].sort((first, second) => second[1] - first[1] || first[0] - second[0])[0]?.[0] ?? 0;
}

function placementBestWindowForColor({ tile, bounds, color, cameraCenterX = 0, cameraCenterY = 0 }) {
  const cells = Array.isArray(tile?.cells) ? tile.cells : [];
  const width = bounds.width;
  const height = bounds.height;
  const candidates = [];
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      if (cells[y * width + x] !== color) continue;
      const minX = Math.max(0, x - 6);
      const minY = Math.max(0, y - 6);
      const maxX = Math.min(width - 1, minX + 11);
      const maxY = Math.min(height - 1, minY + 11);
      let count = 0;
      for (let windowY = minY; windowY <= maxY; windowY += 1) {
        for (let windowX = minX; windowX <= maxX; windowX += 1) {
          if (cells[windowY * width + windowX] === color) count += 1;
        }
      }
      const anchorX = bounds.offset_x + x;
      const anchorY = bounds.offset_y + y;
      candidates.push({
        count,
        x,
        y,
        minX,
        minY,
        maxX,
        maxY,
        distance: Math.hypot(anchorX - cameraCenterX, anchorY - cameraCenterY),
      });
    }
  }
  candidates.sort((first, second) => (
    second.count - first.count
    || first.distance - second.distance
    || first.y - second.y
    || first.x - second.x
  ));
  return candidates[0] || null;
}

function placementInitialTargetCell({ width, height, tileSize, tiles, preferredColor = null }) {
  const byKey = placementTileMap(tiles);
  const color = Number.isInteger(preferredColor) ? preferredColor : placementDominantColor(tiles);
  const centerX = width / 2;
  const centerY = height / 2;
  const candidates = [];
  for (const tile of tiles || []) {
    const tileX = Number(tile.tile_x);
    const tileY = Number(tile.tile_y);
    const bounds = getTileBounds({ width, height, tileSize, tileX, tileY });
    const counts = placementTileColorCounts(tile);
    const remaining = counts.get(color) || 0;
    if (!remaining) continue;
    const distance = Math.hypot(tileX * tileSize + tileSize / 2 - centerX, tileY * tileSize + tileSize / 2 - centerY);
    candidates.push({ tile, bounds, tileX, tileY, remaining, distance });
  }
  candidates.sort((first, second) => (
    (-second.distance + Math.min(second.remaining, 512) * 0.05)
      - (-first.distance + Math.min(first.remaining, 512) * 0.05)
    || first.tileY - second.tileY
    || first.tileX - second.tileX
  ));
  const selected = candidates[0];
  if (!selected || !byKey.has(`${selected.tileX}:${selected.tileY}`)) return null;
  const window = placementBestWindowForColor({
    tile: selected.tile,
    bounds: selected.bounds,
    color,
    cameraCenterX: centerX,
    cameraCenterY: centerY,
  });
  if (!window) return null;
  const digest = placementHashString(`early:${selected.tileX}:${selected.tileY}:${window.minX}:${window.minY}`);
  const selectedCells = Array.isArray(selected.tile.cells) ? selected.tile.cells : [];
  const matching = [];
  for (let y = window.minY; y <= window.maxY; y += 1) {
    for (let x = window.minX; x <= window.maxX; x += 1) {
      if (selectedCells[y * selected.bounds.width + x] === color) matching.push({ x, y });
    }
  }
  if (!matching.length) return null;
  const picked = matching[digest.readUInt32BE(0) % matching.length];
  const localIndex = picked.y * selected.bounds.width + picked.x;
  return {
    tile: selected.tile,
    tileX: selected.tileX,
    tileY: selected.tileY,
    localIndex,
    cellIndex: (selected.bounds.offset_y + picked.y) * width + selected.bounds.offset_x + picked.x,
    color,
    bounds: {
      minX: selected.bounds.offset_x + window.minX,
      minY: selected.bounds.offset_y + window.minY,
      maxX: selected.bounds.offset_x + window.maxX,
      maxY: selected.bounds.offset_y + window.maxY,
    },
  };
}

function placementMacroRegions(width, height) {
  const columns = Math.ceil(width / SPARK_MACRO_REGION_SIZE);
  const rows = Math.ceil(height / SPARK_MACRO_REGION_SIZE);
  return Array.from({ length: rows * columns }, (_, index) => {
    const x = index % columns;
    const y = Math.floor(index / columns);
    return {
      x,
      y,
      width: Math.min(SPARK_MACRO_REGION_SIZE, width - x * SPARK_MACRO_REGION_SIZE),
      height: Math.min(SPARK_MACRO_REGION_SIZE, height - y * SPARK_MACRO_REGION_SIZE),
    };
  });
}

function placementRegionQuotas(total, regions, requiredRegion) {
  const quotas = regions.map(() => Math.floor(total / Math.max(1, regions.length)));
  let remainder = total - quotas.reduce((sum, value) => sum + value, 0);
  const order = regions
    .map((region, index) => ({ index, rank: placementFnvHash(`quota:${region.x}:${region.y}`) }))
    .sort((first, second) => first.rank - second.rank);
  while (remainder > 0) {
    quotas[order[remainder % order.length].index] += 1;
    remainder -= 1;
  }
  if (requiredRegion != null && quotas[requiredRegion] === 0) {
    const donor = quotas.findIndex((quota, index) => index !== requiredRegion && quota > 1);
    if (donor >= 0) {
      quotas[donor] -= 1;
      quotas[requiredRegion] += 1;
    } else {
      const fallback = quotas.findIndex((quota, index) => index !== requiredRegion && quota > 0);
      if (fallback >= 0) {
        quotas[fallback] -= 1;
        quotas[requiredRegion] += 1;
      }
    }
  }
  return quotas;
}

function placementCandidateInRegion({ region, quota, seed, ordinal, occupied, width, tileSize, byKey }) {
  if (!quota) return [];
  const subColumns = Math.max(1, Math.ceil(Math.sqrt(quota * region.width / Math.max(1, region.height))));
  const subRows = Math.max(1, Math.ceil(quota / subColumns));
  const slots = Array.from({ length: subRows * subColumns }, (_, index) => index)
    .sort((first, second) => placementFnvHash(`${seed}:region:${region.x}:${region.y}:${first}`)
      - placementFnvHash(`${seed}:region:${region.x}:${region.y}:${second}`));
  const result = [];
  for (let index = 0; index < quota; index += 1) {
    const slot = slots[index];
    const slotX = slot % subColumns;
    const slotY = Math.floor(slot / subColumns);
    const minX = region.x * SPARK_MACRO_REGION_SIZE + Math.floor(slotX * region.width / subColumns);
    const maxX = region.x * SPARK_MACRO_REGION_SIZE + Math.min(region.width - 1, Math.floor((slotX + 1) * region.width / subColumns) - 1);
    const minY = region.y * SPARK_MACRO_REGION_SIZE + Math.floor(slotY * region.height / subRows);
    const maxY = region.y * SPARK_MACRO_REGION_SIZE + Math.min(region.height - 1, Math.floor((slotY + 1) * region.height / subRows) - 1);
    const digest = placementHashString(`${seed}:region:${region.x}:${region.y}:${ordinal}:${slot}`);
    let picked = null;
    const spanX = Math.max(1, maxX - minX + 1);
    const spanY = Math.max(1, maxY - minY + 1);
    for (let attempt = 0; attempt < spanX * spanY; attempt += 1) {
      const offset = (digest.readUInt32BE(0) + attempt) % (spanX * spanY);
      const x = minX + (offset % spanX);
      const y = minY + Math.floor(offset / spanX);
      const cellIndex = y * width + x;
      const tileX = Math.floor(x / tileSize);
      const tileY = Math.floor(y / tileSize);
      if (!byKey.has(`${tileX}:${tileY}`) || occupied.has(cellIndex)) continue;
      picked = { x, y, cellIndex, tileX, tileY };
      break;
    }
    if (picked) {
      occupied.add(picked.cellIndex);
      result.push(picked);
    }
  }
  return result;
}

export function generateParameterizedSparkCells({
  templateId,
  seed = templateId,
  width,
  height,
  tileSize = 32,
  tiles,
  earlyColor = null,
  densityCells = DEFAULT_DENSITY_CELLS,
  maxSpecials = DEFAULT_MAX_SPECIALS,
} = {}) {
  const grid = getTileGrid(width, height, tileSize);
  const orderedTiles = [...(tiles || [])]
    .filter((tile) => Array.isArray(tile?.cells))
    .sort((a, b) => Number(a.tile_y) - Number(b.tile_y) || Number(a.tile_x) - Number(b.tile_x));
  if (!orderedTiles.length) return [];
  const generationSeed = `${seed}:${grid.width}:${grid.height}:${SPECIAL_GENERATION_VERSION}`;
  const count = Math.min(maxSpecials, Math.max(1, Math.ceil(grid.totalCells / densityCells)));
  const byKey = placementTileMap(orderedTiles);
  const occupied = new Set();
  const early = placementInitialTargetCell({
    width: grid.width,
    height: grid.height,
    tileSize: grid.tile_size,
    tiles: orderedTiles,
    preferredColor: earlyColor,
  });
  const regions = placementMacroRegions(grid.width, grid.height);
  const macroColumns = Math.ceil(grid.width / SPARK_MACRO_REGION_SIZE);
  const earlyRegion = early
    ? Math.floor(Math.floor(early.cellIndex / grid.width) / SPARK_MACRO_REGION_SIZE) * macroColumns
      + Math.floor((early.cellIndex % grid.width) / SPARK_MACRO_REGION_SIZE)
    : null;
  const quotas = placementRegionQuotas(count, regions, earlyRegion);
  const result = [];
  if (early) {
    occupied.add(early.cellIndex);
    result.push({
      special_id: `sc_early_${placementHashString(`${generationSeed}:${early.cellIndex}`).toString('hex').slice(0, 16)}`,
      kind: SPARK_KIND,
      cell_index: early.cellIndex,
      tile_x: early.tileX,
      tile_y: early.tileY,
      local_index: early.localIndex,
      generation_version: SPECIAL_GENERATION_VERSION,
    });
    quotas[earlyRegion] = Math.max(0, quotas[earlyRegion] - 1);
  }
  for (let regionIndex = 0; regionIndex < regions.length && result.length < count; regionIndex += 1) {
    const region = regions[regionIndex];
    const candidates = placementCandidateInRegion({
      region,
      quota: quotas[regionIndex],
      seed: generationSeed,
      ordinal: regionIndex,
      occupied,
      width: grid.width,
      tileSize: grid.tile_size,
      byKey,
    });
    for (const candidate of candidates) {
      if (result.length >= count) break;
      const tile = byKey.get(`${candidate.tileX}:${candidate.tileY}`);
      const bounds = getTileBounds({
        width: grid.width,
        height: grid.height,
        tileSize: grid.tile_size,
        tileX: candidate.tileX,
        tileY: candidate.tileY,
      });
      const localIndex = (candidate.y - bounds.offset_y) * bounds.width + candidate.x - bounds.offset_x;
      result.push({
        special_id: `sc_${placementHashString(`${generationSeed}:${candidate.cellIndex}`).toString('hex').slice(0, 16)}`,
        kind: SPARK_KIND,
        cell_index: candidate.cellIndex,
        tile_x: bounds.tile_x,
        tile_y: bounds.tile_y,
        local_index: localIndex,
        generation_version: SPECIAL_GENERATION_VERSION,
        color: tile?.cells?.[localIndex] ?? null,
      });
    }
  }
  return result.map(({ color: _color, ...cell }) => cell);
}

/**
 * Mirrors the production multi-kind cycle (first candidate always Spark, the
 * rest assigned deterministically from the candidate cell). Existing baseline
 * runs stay Spark-only; this is used only when the caller opts into the event
 * mix.
 */
export function assignEventKinds(cells, {
  seed,
  width,
  height,
  kindPattern = SPECIAL_KIND_PATTERN,
} = {}) {
  if (!cells?.length) return [];
  const generationSeed = `${seed}:${width}:${height}:${SPECIAL_GAMEPLAY_GENERATION_VERSION}`;
  const cycleOffset = placementFnvHash(`${generationSeed}:weighted-cycle`) % kindPattern.length;
  return cells.map((cell, index) => {
    let kind = SPARK_KIND;
    if (index >= 1 && index <= 3) {
      kind = [SPARK_KIND, BOMB_KIND, SPARK_KIND][index - 1];
    } else if (index > 3) {
      kind = kindPattern[(index - 4 + cycleOffset) % kindPattern.length];
    }
    return {
      ...cell,
      kind,
      generation_version: SPECIAL_GAMEPLAY_GENERATION_VERSION,
      kind_meta: normalizeSpecialKind(kind),
    };
  });
}

function placementSparkDistance(first, second, width) {
  const firstX = first.cell_index % width;
  const firstY = Math.floor(first.cell_index / width);
  const secondX = second.cell_index % width;
  const secondY = Math.floor(second.cell_index / width);
  return Math.hypot(firstX - secondX, firstY - secondY);
}

function placementInitialRouteTarget({ width, height, tileSize, tile, color }) {
  const bounds = getTileBounds({ width, height, tileSize, tileX: Number(tile.tile_x), tileY: Number(tile.tile_y) });
  const window = placementBestWindowForColor({
    tile,
    bounds,
    color,
    cameraCenterX: width / 2,
    cameraCenterY: height / 2,
  });
  if (!window) return null;
  return {
    tile_x: Number(tile.tile_x),
    tile_y: Number(tile.tile_y),
    min_x: bounds.offset_x + window.minX,
    min_y: bounds.offset_y + window.minY,
    max_x: bounds.offset_x + window.maxX,
    max_y: bounds.offset_y + window.maxY,
  };
}

export function diagnoseParameterizedSparkPlacement({
  templateId,
  seed = templateId,
  width,
  height,
  tileSize = 32,
  tiles,
  densityCells = DEFAULT_DENSITY_CELLS,
  maxSpecials = DEFAULT_MAX_SPECIALS,
} = {}) {
  const grid = getTileGrid(width, height, tileSize);
  const generated = generateParameterizedSparkCells({
    templateId,
    seed,
    width,
    height,
    tileSize,
    tiles,
    densityCells,
    maxSpecials,
  });
  const regions = placementMacroRegions(grid.width, grid.height);
  const macroCounts = regions.map((region) => ({
    region_x: region.x,
    region_y: region.y,
    count: generated.filter((cell) => (
      Math.floor((cell.cell_index % grid.width) / SPARK_MACRO_REGION_SIZE) === region.x
      && Math.floor(Math.floor(cell.cell_index / grid.width) / SPARK_MACRO_REGION_SIZE) === region.y
    )).length,
  }));
  const byKey = placementTileMap(tiles);
  const colors = {};
  for (const cell of generated) {
    const tile = byKey.get(`${cell.tile_x}:${cell.tile_y}`);
    const color = tile?.cells?.[cell.local_index];
    colors[color] = (colors[color] || 0) + 1;
  }
  const distances = [];
  for (let index = 1; index < generated.length; index += 1) {
    let nearest = Infinity;
    for (let previous = 0; previous < index; previous += 1) {
      nearest = Math.min(nearest, placementSparkDistance(generated[index], generated[previous], grid.width));
    }
    distances.push(nearest);
  }
  const orderedTiles = [...(tiles || [])].sort((a, b) => Number(a.tile_y) - Number(b.tile_y) || Number(a.tile_x) - Number(b.tile_x));
  const color = placementDominantColor(orderedTiles);
  const centerX = grid.width / 2;
  const centerY = grid.height / 2;
  const ranked = orderedTiles.map((tile) => {
    const count = placementTileColorCounts(tile).get(color) || 0;
    const distance = Math.hypot(Number(tile.tile_x) * grid.tile_size + grid.tile_size / 2 - centerX,
      Number(tile.tile_y) * grid.tile_size + grid.tile_size / 2 - centerY);
    return { tile, count, score: -distance + Math.min(count, 512) * 0.05 };
  }).filter((entry) => entry.count > 0)
    .sort((first, second) => second.score - first.score || Number(first.tile.tile_y) - Number(second.tile.tile_y)
      || Number(first.tile.tile_x) - Number(second.tile.tile_x));
  let firstSparkTarget = null;
  for (let index = 0; index < ranked.length; index += 1) {
    const target = placementInitialRouteTarget({
      width: grid.width,
      height: grid.height,
      tileSize: grid.tile_size,
      tile: ranked[index].tile,
      color,
    });
    if (!target) continue;
    if (generated.some((cell) => cell.cell_index % grid.width >= target.min_x
      && cell.cell_index % grid.width <= target.max_x
      && Math.floor(cell.cell_index / grid.width) >= target.min_y
      && Math.floor(cell.cell_index / grid.width) <= target.max_y
      && byKey.get(`${cell.tile_x}:${cell.tile_y}`))) {
      firstSparkTarget = index + 1;
      break;
    }
  }
  const targetCount = generated.length ? firstSparkTarget : null;
  return {
    template_id: templateId,
    seed,
    total_cells: grid.totalCells,
    spark_count: generated.length,
    density_cells_per_spark: generated.length ? grid.totalCells / generated.length : null,
    macro_region_size: SPARK_MACRO_REGION_SIZE,
    macro_region_columns: Math.ceil(grid.width / SPARK_MACRO_REGION_SIZE),
    macro_region_rows: Math.ceil(grid.height / SPARK_MACRO_REGION_SIZE),
    spark_count_by_macro_region: macroCounts,
    spark_count_by_color: colors,
    nearest_neighbor_distance: {
      min: distances.length ? Math.min(...distances) : null,
      average: distances.length ? distances.reduce((sum, value) => sum + value, 0) / distances.length : null,
      max: distances.length ? Math.max(...distances) : null,
    },
    smart_engine: {
      dominant_color: color,
      expected_targets_to_first_spark: targetCount,
      worst_case_early_route_without_spark: targetCount == null ? ranked.length : Math.max(0, targetCount - 1),
      early_target_guaranteed: targetCount === 1,
    },
  };
}

/**
 * Equivalent window selection to the production chooseActionableWindow but
 * built on an integral image so it stays bounded for 1200x1200 tiles.
 */
export function chooseActionableWindowFast({
  cells,
  filled,
  width,
  height,
  colorIndex,
  offsetX = 0,
  offsetY = 0,
  cameraCenterX = 0,
  cameraCenterY = 0,
  windowSize = ACTIONABLE_WINDOW_SIZE,
} = {}) {
  if (!cells || !filled || width <= 0 || height <= 0) return null;
  const size = Math.max(1, Math.floor(Number(windowSize) || ACTIONABLE_WINDOW_SIZE));
  const matrix = new Int8Array(width * height);
  for (let index = 0; index < cells.length; index += 1) {
    if (filled[index] === -1 && cells[index] === colorIndex) matrix[index] = 1;
  }
  const rowStride = width + 1;
  const sums = new Int32Array(rowStride * (height + 1));
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      sums[(y + 1) * rowStride + x + 1] =
        matrix[y * width + x]
        + sums[y * rowStride + x + 1]
        + sums[(y + 1) * rowStride + x]
        - sums[y * rowStride + x];
    }
  }
  const candidates = [];
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      const index = y * width + x;
      if (filled[index] !== -1 || cells[index] !== colorIndex) continue;
      const minX = Math.max(0, x - Math.floor(size / 2));
      const minY = Math.max(0, y - Math.floor(size / 2));
      const maxX = Math.min(width - 1, minX + size - 1);
      const maxY = Math.min(height - 1, minY + size - 1);
      const count =
        sums[(maxY + 1) * rowStride + maxX + 1]
        - sums[minY * rowStride + maxX + 1]
        - sums[(maxY + 1) * rowStride + minX]
        + sums[minY * rowStride + minX];
      if (count <= 0) continue;
      const anchorX = offsetX + x;
      const anchorY = offsetY + y;
      const distance = Math.hypot(anchorX - cameraCenterX, anchorY - cameraCenterY);
      candidates.push({ count, distance, anchorX, anchorY, minX, minY, maxX, maxY });
    }
  }
  if (!candidates.length) return null;
  candidates.sort((first, second) => (
    second.count - first.count
    || first.distance - second.distance
    || first.anchorY - second.anchorY
    || first.anchorX - second.anchorX
  ));
  const best = candidates[0];
  return {
    anchor_x: best.anchorX,
    anchor_y: best.anchorY,
    bounds: {
      min_x: offsetX + best.minX,
      min_y: offsetY + best.minY,
      max_x: offsetX + best.maxX,
      max_y: offsetY + best.maxY,
      width: best.maxX - best.minX + 1,
      height: best.maxY - best.minY + 1,
    },
    estimated_cells: best.count,
  };
}

function sparkWindow({ tile, filled, bounds, spark, color }) {
  const localX = Number(spark.local_index) % bounds.width;
  const localY = Math.floor(Number(spark.local_index) / bounds.width);
  const minLocalX = Math.max(0, localX - 6);
  const minLocalY = Math.max(0, localY - 6);
  const maxLocalX = Math.min(bounds.width - 1, minLocalX + 11);
  const maxLocalY = Math.min(bounds.height - 1, minLocalY + 11);
  let estimatedCells = 0;
  for (let y = minLocalY; y <= maxLocalY; y += 1) {
    for (let x = minLocalX; x <= maxLocalX; x += 1) {
      const index = y * bounds.width + x;
      if (filled[index] === -1 && tile.cells[index] === color) estimatedCells += 1;
    }
  }
  return {
    tile_x: bounds.tile_x,
    tile_y: bounds.tile_y,
    color,
    anchor_x: bounds.offset_x + localX,
    anchor_y: bounds.offset_y + localY,
    bounds: {
      min_x: bounds.offset_x + minLocalX,
      min_y: bounds.offset_y + minLocalY,
      max_x: bounds.offset_x + maxLocalX,
      max_y: bounds.offset_y + maxLocalY,
      width: maxLocalX - minLocalX + 1,
      height: maxLocalY - minLocalY + 1,
    },
    estimated_cells: estimatedCells,
  };
}

function sparkClusters(sparks, width, threshold = SPARK_CLUSTER_THRESHOLD_CELLS) {
  const positions = sparks.map((spark) => ({
    x: Number(spark.cell_index) % width,
    y: Math.floor(Number(spark.cell_index) / width),
  }));
  const parent = positions.map((_, index) => index);
  const find = (index) => {
    let root = index;
    while (parent[root] !== root) root = parent[root];
    while (parent[index] !== index) {
      const next = parent[index];
      parent[index] = root;
      index = next;
    }
    return root;
  };
  const union = (first, second) => {
    const firstRoot = find(first);
    const secondRoot = find(second);
    if (firstRoot !== secondRoot) parent[secondRoot] = firstRoot;
  };
  for (let first = 0; first < positions.length; first += 1) {
    for (let second = first + 1; second < positions.length; second += 1) {
      const dx = positions[first].x - positions[second].x;
      const dy = positions[first].y - positions[second].y;
      if (Math.hypot(dx, dy) <= threshold) union(first, second);
    }
  }
  const sizes = new Map();
  for (let index = 0; index < positions.length; index += 1) {
    const root = find(index);
    sizes.set(root, (sizes.get(root) || 0) + 1);
  }
  const clusterSizes = [...sizes.values()].sort((first, second) => first - second);
  const sizeSummary = percentileWithAverage(clusterSizes);
  return {
    threshold,
    count: clusterSizes.length,
    min_size: sizeSummary.min,
    average_size: sizeSummary.avg,
    max_size: sizeSummary.max,
    p50_size: sizeSummary.p50,
    p90_size: sizeSummary.p90,
    p95_size: sizeSummary.p95,
    sizes: clusterSizes,
  };
}

function createRouteState({ template, tiles, sparks }) {
  const tileByKey = new Map();
  const boundsByKey = new Map();
  const filledByKey = new Map();
  const remainingByTile = new Map();
  const remainingByColor = new Map();
  const remainingTilesByColor = new Map();
  const sparkByTileLocal = new Map();

  for (const tile of tiles) {
    const key = keyOf(Number(tile.tile_x), Number(tile.tile_y));
    const bounds = getTileBounds({
      width: template.width,
      height: template.height,
      tileSize: template.tile_size,
      tileX: Number(tile.tile_x),
      tileY: Number(tile.tile_y),
    });
    tileByKey.set(key, tile);
    boundsByKey.set(key, bounds);
    filledByKey.set(key, new Int8Array(tile.cells.length).fill(-1));
    const counts = new Map();
    for (const color of tile.cells) {
      if (!Number.isInteger(color) || color < 0) continue;
      counts.set(color, (counts.get(color) || 0) + 1);
      remainingByColor.set(color, (remainingByColor.get(color) || 0) + 1);
    }
    remainingByTile.set(key, counts);
    for (const [color] of counts) {
      if (!remainingTilesByColor.has(color)) remainingTilesByColor.set(color, new Set());
      remainingTilesByColor.get(color).add(key);
    }
  }

  for (const spark of sparks) {
    const key = keyOf(Number(spark.tile_x), Number(spark.tile_y));
    if (!sparkByTileLocal.has(key)) sparkByTileLocal.set(key, new Map());
    sparkByTileLocal.get(key).set(Number(spark.local_index), spark);
  }

  const sparksSorted = [...sparks].sort((first, second) => {
    const firstEarly = String(first.special_id).startsWith('sc_early_') ? 0 : 1;
    const secondEarly = String(second.special_id).startsWith('sc_early_') ? 0 : 1;
    return firstEarly - secondEarly || Number(first.cell_index) - Number(second.cell_index);
  });

  return {
    template,
    tileByKey,
    boundsByKey,
    filledByKey,
    remainingByTile,
    remainingByColor,
    remainingTilesByColor,
    sparkByTileLocal,
    sparksSorted,
    claimed: new Set(),
    completedCells: 0,
    eventCount: 0,
    sparkEventCount: 0,
    camera: { x: template.width / 2, y: template.height / 2 },
  };
}

function pushRecent(recentList, key) {
  const without = recentList.filter((entry) => entry !== key);
  without.push(key);
  return without.slice(-GUIDANCE_MAX_RECENT);
}

function mostRemainingColor(state) {
  const colors = [...state.remainingByColor.entries()]
    .filter(([, remaining]) => remaining > 0)
    .sort((first, second) => second[1] - first[1] || first[0] - second[0]);
  return colors[0]?.[0] ?? null;
}

function remainingTiles(state, color, recentSet) {
  const keys = state.remainingTilesByColor.get(color);
  if (!keys) return [];
  const result = [];
  for (const key of keys) {
    if (recentSet.has(key)) continue;
    const remaining = state.remainingByTile.get(key).get(color) || 0;
    if (remaining <= 0) continue;
    const tile = state.tileByKey.get(key);
    const size = state.template.tile_size;
    const tileCenterX = Number(tile.tile_x) * size + size / 2;
    const tileCenterY = Number(tile.tile_y) * size + size / 2;
    const distance = Math.hypot(tileCenterX - state.camera.x, tileCenterY - state.camera.y);
    result.push({ key, distance, remaining, score: -distance + Math.min(remaining, 512) * 0.05 });
  }
  result.sort((first, second) => second.score - first.score);
  return result;
}

function bestTarget(state, color, recentSet) {
  const candidates = remainingTiles(state, color, recentSet);
  if (!candidates.length) return null;
  const candidate = candidates[0];
  const tile = state.tileByKey.get(candidate.key);
  const bounds = state.boundsByKey.get(candidate.key);
  const target = chooseActionableWindowFast({
    cells: tile.cells,
    filled: state.filledByKey.get(candidate.key),
    width: bounds.width,
    height: bounds.height,
    colorIndex: color,
    offsetX: bounds.offset_x,
    offsetY: bounds.offset_y,
    cameraCenterX: state.camera.x,
    cameraCenterY: state.camera.y,
  });
  if (!target) return null;
  return { tileKey: candidate.key, target };
}

function findFirstUnfilledSpark(state) {
  for (const spark of state.sparksSorted) {
    // The production pity contract is Spark-only. Event-mix candidates share
    // the same route simulator, so explicitly skip Bomb/Fuse/Choice/Artifact
    // instead of letting a mixed candidate accidentally become a pity event.
    if (String(spark.kind || SPARK_KIND) !== SPARK_KIND) continue;
    if (state.claimed.has(String(spark.special_id))) continue;
    const key = keyOf(Number(spark.tile_x), Number(spark.tile_y));
    const tile = state.tileByKey.get(key);
    const filled = state.filledByKey.get(key);
    if (filled[Number(spark.local_index)] !== -1) continue;
    const color = Number(tile.cells[Number(spark.local_index)]);
    const target = sparkWindow({
      tile,
      filled,
      bounds: state.boundsByKey.get(key),
      spark,
      color,
    });
    if (target.estimated_cells <= 0) continue;
    return { spark, key, color, target };
  }
  return null;
}

function paintCells(state, {
  tileKey,
  color,
  bounds,
  cap = Infinity,
}) {
  const tile = state.tileByKey.get(tileKey);
  const tileBounds = state.boundsByKey.get(tileKey);
  const filled = state.filledByKey.get(tileKey);
  const counts = state.remainingByTile.get(tileKey);
  const minX = Math.max(tileBounds.offset_x, bounds.min_x);
  const minY = Math.max(tileBounds.offset_y, bounds.min_y);
  const maxX = Math.min(tileBounds.offset_x + tileBounds.width - 1, bounds.max_x);
  const maxY = Math.min(tileBounds.offset_y + tileBounds.height - 1, bounds.max_y);
  const paintedCells = [];
  let count = 0;
  for (let y = minY; y <= maxY && count < cap; y += 1) {
    for (let x = minX; x <= maxX && count < cap; x += 1) {
      const localIndex = (y - tileBounds.offset_y) * tileBounds.width + (x - tileBounds.offset_x);
      if (filled[localIndex] !== -1 || tile.cells[localIndex] !== color) continue;
      filled[localIndex] = 1;
      counts.set(color, (counts.get(color) || 1) - 1);
      if ((counts.get(color) || 0) <= 0) {
        state.remainingTilesByColor.get(color)?.delete(tileKey);
      }
      state.remainingByColor.set(color, (state.remainingByColor.get(color) || 1) - 1);
      paintedCells.push({ tileKey, localIndex, globalIndex: y * state.template.width + x, color });
      count += 1;
    }
  }
  return { count, paintedCells };
}

function placementMetrics(template, sparks, placement) {
  const regions = placement.spark_count_by_macro_region || [];
  const coveredRegions = regions.filter((entry) => entry.count > 0).length;
  const kindCounts = {};
  const perTile = new Map();
  for (const spark of sparks) {
    const kind = String(spark.kind || SPARK_KIND);
    kindCounts[kind] = (kindCounts[kind] || 0) + 1;
    const key = `${spark.tile_x}:${spark.tile_y}`;
    perTile.set(key, (perTile.get(key) || 0) + 1);
  }
  const trapCount = sparks.filter((spark) => TRAP_KINDS.includes(String(spark.kind))).length;
  const rareCount = sparks.filter((spark) => RARE_KINDS.includes(String(spark.kind))).length;
  const distances = [];
  for (let index = 1; index < sparks.length; index += 1) {
    let nearest = Infinity;
    for (let previous = 0; previous < index; previous += 1) {
      nearest = Math.min(nearest, placementSparkDistance(sparks[index], sparks[previous], template.width));
    }
    distances.push(nearest);
  }
  const nearestNeighborDistance = percentileWithAverage(distances);
  return {
    ...placement,
    regions_total: regions.length,
    regions_covered: coveredRegions,
    region_coverage_ratio: regions.length ? coveredRegions / regions.length : null,
    colors_total: template.palette.length,
    spark_colors: Object.keys(placement.spark_count_by_color || {}).length,
    clusters: sparkClusters(sparks, template.width),
    nearest_neighbor_distance: {
      ...nearestNeighborDistance,
      average: nearestNeighborDistance.avg,
      distances,
    },
    kind_counts: kindCounts,
    max_specials_per_tile: perTile.size ? Math.max(...perTile.values()) : null,
    trap_count: trapCount,
    rare_count: rareCount,
    trap_rate: sparks.length ? trapCount / sparks.length : null,
    rare_rate: sparks.length ? rareCount / sparks.length : null,
  };
}

/**
 * Run one deterministic Spark-only gameplay simulation.
 */
export function simulateSpecialGameplay({
  width,
  height,
  seed,
  tileSize = DEFAULT_TILE_SIZE,
  paletteSize = DEFAULT_PALETTE_SIZE,
  templateSeed = 'synthetic-artwork-v1',
  maxPlans = DEFAULT_MAX_PLANS,
  densityCells = DEFAULT_DENSITY_CELLS,
  maxSpecials = DEFAULT_MAX_SPECIALS,
  eventMix = EVENT_MIX_DEFAULT,
  includeHazard = false,
  hazardMode = null,
  sparkTreatment = true,
  artwork = null,
} = {}) {
  const effectiveHazardMode = hazardMode || (includeHazard ? 'separate' : 'none');
  if (effectiveHazardMode !== 'none' && !eventMix) {
    throw new Error('hazardMode requires eventMix; Spark-only baseline must not silently add hazard');
  }
  if (!Number.isFinite(densityCells) || densityCells <= 0) {
    throw new Error(`densityCells must be a positive number, got ${densityCells}`);
  }
  if (!Number.isFinite(maxSpecials) || maxSpecials <= 0) {
    throw new Error(`maxSpecials must be a positive number, got ${maxSpecials}`);
  }
  const grid = getTileGrid(width, height, tileSize);
  const productionMixDefaults = eventMix
    && densityCells === DEFAULT_DENSITY_CELLS
    && maxSpecials === DEFAULT_MAX_SPECIALS;
  const effectiveDensityCells = productionMixDefaults
    ? specialDensityForGrid(grid.width, grid.height)
    : densityCells;
  const effectiveMaxSpecials = productionMixDefaults
    ? SPECIAL_EVENT_MAX_CELLS
    : maxSpecials;
  const built = artwork || buildSyntheticTemplate({
    width: grid.width,
    height: grid.height,
    tileSize: grid.tile_size,
    paletteSize,
    seed: templateSeed,
  });
  const template = built.template;
  const tiles = built.tiles;
  const parameterizedPlacement = effectiveDensityCells !== SPARK_DENSITY_CELLS
    || effectiveMaxSpecials !== SPARK_MAX_CELLS;
  const placementOptions = {
    templateId: template.id,
    seed,
    width: grid.width,
    height: grid.height,
    tileSize: grid.tile_size,
    tiles,
  };
  const generated = generateSparkCells({
    ...placementOptions,
    densityCells: effectiveDensityCells,
    maxSpecials: effectiveMaxSpecials,
  });
  const kindAdapter = eventMix ? resolveEventKindMix({ includeHazard, hazardMode: effectiveHazardMode }) : null;
  let sparks = eventMix
    ? assignEventKinds(capSpecialsPerTile(generated), {
        seed,
        width: grid.width,
        height: grid.height,
        kindPattern: kindAdapter.pattern,
      })
    : generated;
  if (effectiveHazardMode === 'separate' || effectiveHazardMode === 'both') {
    const hazard = generateHazardCells({
      ...placementOptions,
      occupiedIndices: sparks.map((cell) => cell.cell_index),
    });
    sparks = [...sparks, ...hazard];
  }
  const placementReport = parameterizedPlacement
    ? diagnoseParameterizedSparkPlacement({
        ...placementOptions,
        densityCells: effectiveDensityCells,
        maxSpecials: effectiveMaxSpecials,
      })
    : diagnoseSparkPlacement(placementOptions);
  // Production pity is Spark-specific and remains 6000 cells. The denser
  // mixed candidates are discovered by ordinary route painting; they do not
  // silently change Spark guidance semantics.
  const pityIntervalCells = SPARK_PITY_INTERVAL_CELLS;
  const state = createRouteState({ template, tiles, sparks });
  const started = process.hrtime.bigint();
  const recentList = [];
  let recentSet = new Set();
  let selectedColor = null;
  let planIndex = 0;
  let regularTargets = 0;
  let sparkPlans = 0;
  let noOpPlans = 0;
  let candidateEvaluations = 0;
  let guidedCells = 0;
  let assistedCells = 0;
  let truncated = false;
  const events = [];
  const gapsCells = [];
  const gapsTargets = [];
  let firstSparkPlanIndex = null;
  let nonSparkBeforeFirst = 0;
  let firstEventPlanIndex = null;
  let nonSparkBeforeFirstEvent = 0;
  let firstEventKind = null;

  const triggerClaims = (paintedCells, discoveredByPity = false, planType = 'regular') => {
    for (const painted of paintedCells) {
      const spark = state.sparkByTileLocal.get(painted.tileKey)?.get(painted.localIndex);
      if (!spark || state.claimed.has(String(spark.special_id))) continue;
      state.claimed.add(String(spark.special_id));
      state.eventCount += 1;
      const kind = String(spark.kind || SPARK_KIND);
      if (kind === SPARK_KIND) state.sparkEventCount += 1;
      if (kind === SPARK_KIND && firstSparkPlanIndex == null) {
        firstSparkPlanIndex = planIndex;
        nonSparkBeforeFirst = planType === 'spark_plan'
          ? regularTargets
          : Math.max(0, regularTargets - 1);
      }
      const gapCells = events.length ? state.completedCells - events[events.length - 1].completed_cells : null;
      const gapTargets = events.length ? planIndex - events[events.length - 1].plan_index - 1 : null;
      if (gapCells != null) gapsCells.push(gapCells);
      if (gapTargets != null) gapsTargets.push(gapTargets);
      const isFirstEvent = events.length === 0;
      if (isFirstEvent) {
        firstEventPlanIndex = planIndex;
        nonSparkBeforeFirstEvent = planType === 'spark_plan'
          ? regularTargets
          : Math.max(0, regularTargets - 1);
        firstEventKind = kind;
      }

      const useColor = mostRemainingColor(state);
      let eventAssisted = 0;
      let offerTargetKey = null;
      const hazardNoEffect = kind === HAZARD_KIND;
      if (useColor != null && kind !== ARTIFACT_KIND && !hazardNoEffect) {
        const offer = bestTarget(state, useColor, recentSet);
        if (offer) {
          offerTargetKey = offer.tileKey;
          candidateEvaluations += remainingTiles(state, useColor, recentSet).length * 2;
          let effectBounds = offer.target.bounds;
          if (kind === BOMB_KIND || kind === FUSE_KIND) {
            const anchorX = Number(spark.cell_index) % state.template.width;
            const anchorY = Math.floor(Number(spark.cell_index) / state.template.width);
            const radius = kind === BOMB_KIND ? 3 : 2;
            effectBounds = {
              min_x: anchorX - radius,
              min_y: anchorY - radius,
              max_x: anchorX + radius,
              max_y: anchorY + radius,
            };
            offerTargetKey = keyOf(Number(spark.tile_x), Number(spark.tile_y));
          }
          const filled = paintCells(state, {
            tileKey: offerTargetKey,
            color: useColor,
            bounds: effectBounds,
            cap: kind === SPARK_KIND ? SPARK_TARGET_MAX_CELLS : SPECIAL_MAX_DERIVED_CHANGES,
          });
          eventAssisted = filled.count;
          assistedCells += filled.count;
          state.completedCells += filled.count;
        }
      }
      if (offerTargetKey) {
        const nextRecent = pushRecent(recentList, offerTargetKey);
        recentList.splice(0, recentList.length, ...nextRecent);
        recentSet = new Set(recentList);
      }
      events.push({
        plan_index: planIndex,
        special_id: String(spark.special_id),
        kind: String(spark.kind || SPARK_KIND),
        cell_index: Number(spark.cell_index),
        color: painted.color,
        completed_cells: state.completedCells,
        gap_cells: gapCells,
        gap_targets: gapTargets,
        assisted_cells: eventAssisted,
        // A pity-directed window can contain another special cell nearby;
        // only the Spark that caused the pity route is a pity discovery.
        discovered_by_pity: discoveredByPity && kind === SPARK_KIND,
      });
    }
  };

  while (planIndex < maxPlans) {
    const remainingColors = [...state.remainingByColor.entries()]
      .filter(([, remaining]) => remaining > 0)
      .sort((first, second) => second[1] - first[1] || first[0] - second[0]);
    if (!remainingColors.length) break;
    if (selectedColor == null || (state.remainingByColor.get(selectedColor) || 0) <= 0) {
      selectedColor = remainingColors[0][0];
    }
    planIndex += 1;
    const plan = { index: planIndex };

    const earlyDue = sparkTreatment && state.completedCells === 0 && state.sparkEventCount === 0;
    const intervalDue = sparkTreatment
      && state.completedCells >= (state.sparkEventCount + 1) * pityIntervalCells;
    if (earlyDue || intervalDue) {
      const pity = findFirstUnfilledSpark(state);
      if (pity) {
        plan.type = 'spark_plan';
        plan.special_id = String(pity.spark.special_id);
        sparkPlans += 1;
        const painted = paintCells(state, {
          tileKey: pity.key,
          color: pity.color,
          bounds: pity.target.bounds,
        });
        guidedCells += painted.count;
        state.completedCells += painted.count;
        state.camera = { x: pity.target.anchor_x, y: pity.target.anchor_y };
        const nextRecent = pushRecent(recentList, pity.key);
        recentList.splice(0, recentList.length, ...nextRecent);
        recentSet = new Set(recentList);
        if (sparkTreatment) triggerClaims(painted.paintedCells, true, 'spark_plan');
        plan.completed_cells = state.completedCells;
        plan.painted_cells = painted.count;
        plan.spark_pity = true;
        continue;
      }
    }

    plan.type = 'regular';
    const candidates = remainingTiles(state, selectedColor, recentSet);
    candidateEvaluations += candidates.length;
    if (!candidates.length) {
      if (recentList.length) {
        recentList.length = 0;
        recentSet = new Set();
        noOpPlans += 1;
        continue;
      }
      selectedColor = remainingColors[0][0];
      noOpPlans += 1;
      continue;
    }
    const candidate = candidates[0];
    const tile = state.tileByKey.get(candidate.key);
    const bounds = state.boundsByKey.get(candidate.key);
    const target = chooseActionableWindowFast({
      cells: tile.cells,
      filled: state.filledByKey.get(candidate.key),
      width: bounds.width,
      height: bounds.height,
      colorIndex: selectedColor,
      offsetX: bounds.offset_x,
      offsetY: bounds.offset_y,
      cameraCenterX: state.camera.x,
      cameraCenterY: state.camera.y,
    });
    const paintBounds = target?.bounds || {
      min_x: bounds.offset_x,
      min_y: bounds.offset_y,
      max_x: bounds.offset_x + bounds.width - 1,
      max_y: bounds.offset_y + bounds.height - 1,
    };
    const painted = paintCells(state, {
      tileKey: candidate.key,
      color: selectedColor,
      bounds: paintBounds,
    });
    guidedCells += painted.count;
    state.completedCells += painted.count;
    regularTargets += 1;
    const anchorX = target?.anchor_x ?? (bounds.offset_x + bounds.width / 2);
    const anchorY = target?.anchor_y ?? (bounds.offset_y + bounds.height / 2);
    state.camera = { x: anchorX, y: anchorY };
    const nextRecent = pushRecent(recentList, candidate.key);
    recentList.splice(0, recentList.length, ...nextRecent);
    recentSet = new Set(recentList);
    if (sparkTreatment) triggerClaims(painted.paintedCells);
    plan.completed_cells = state.completedCells;
    plan.painted_cells = painted.count;
    plan.color = selectedColor;
    plan.tile_key = candidate.key;
    plan.candidates = candidates.length;
    plan.estimated_cells = target?.estimated_cells ?? painted.count;
  }
  if (state.completedCells < grid.totalCells) truncated = true;
  const elapsedMs = Number(process.hrtime.bigint() - started) / 1e6;

  const firstSparkIndex = firstSparkPlanIndex == null ? null : firstSparkPlanIndex;
  const kindMetrics = summarizeKindEventMetrics(events);
  return {
    model: {
      baseline: true,
      gameplay_types: eventMix ? [...kindAdapter.active_kinds] : [...GAMEPLAY_TYPES],
      event_mix: Boolean(eventMix),
      include_hazard: Boolean(includeHazard),
      hazard_mode: effectiveHazardMode,
      mix_generation_version: eventMix ? SPECIAL_GAMEPLAY_GENERATION_VERSION : null,
      route_model: ROUTE_MODEL_VERSION,
      approximation: ROUTE_MODEL_APPROXIMATION,
      kind_adapter: kindAdapter,
      spark_density_cells: effectiveDensityCells,
      spark_pity_interval_cells: pityIntervalCells,
      spark_max_cells: effectiveMaxSpecials,
      spark_derived_changes_cap: SPARK_TARGET_MAX_CELLS,
      macro_region_size: SPARK_MACRO_REGION_SIZE,
      actionable_window_size: ACTIONABLE_WINDOW_SIZE,
      max_recent_tiles: GUIDANCE_MAX_RECENT,
      spark_cluster_threshold_cells: SPARK_CLUSTER_THRESHOLD_CELLS,
      trap_kinds: [...TRAP_KINDS],
      rare_kinds: [...RARE_KINDS],
    },
    template: {
      id: template.id,
      width: template.width,
      height: template.height,
      tile_size: template.tile_size,
      colors_total: template.palette.length,
      total_cells: grid.totalCells,
    },
    seed,
    placement: placementMetrics(template, sparks, placementReport),
    route: {
      completed_cells: state.completedCells,
      total_smart_targets: planIndex,
      regular_targets: regularTargets,
      spark_plans: sparkPlans,
      no_op_plans: noOpPlans,
      spark_events: events.length,
      spark_count: sparks.length,
      special_count: sparks.length,
      missed_sparks: Math.max(0, sparks.length - events.length),
      missed_specials: Math.max(0, sparks.length - events.length),
      discovery_rate: sparks.length ? events.length / sparks.length : null,
      total_candidates: candidateEvaluations,
      smart_targets_to_first_spark: firstSparkIndex,
      non_spark_targets_to_first_spark: nonSparkBeforeFirst,
      smart_targets_to_first_event: firstEventPlanIndex,
      non_spark_targets_to_first_event: nonSparkBeforeFirstEvent,
      first_event_kind: firstEventKind,
      events_per_target: planIndex ? events.length / planIndex : null,
      events_per_regular_target: regularTargets ? events.length / regularTargets : null,
      gaps_cells: gapsCells,
      gaps_cells_summary: percentileSummary(gapsCells),
      gaps_targets: gapsTargets,
      gaps_targets_summary: percentileSummary(gapsTargets),
      events_by_kind: kindMetrics.events_by_kind,
      type_distribution: kindMetrics.type_distribution,
      first_event_by_kind: kindMetrics.first_event_by_kind,
      type_streak: kindMetrics.type_streak,
      gaps_by_kind: kindMetrics.gaps_by_kind,
      trap_events: kindMetrics.trap_events,
      trap_rate: kindMetrics.trap_rate,
      rare_events: kindMetrics.rare_events,
      rare_rate: kindMetrics.rare_rate,
      assisted_cells: assistedCells,
      assisted_cells_by_kind: kindMetrics.assisted_cells_by_kind,
      assisted_progress: kindMetrics.assisted_progress,
      guided_cells: guidedCells,
      assisted_ratio: state.completedCells ? assistedCells / state.completedCells : null,
      assisted_per_event: numericSummary(events.map((event) => event.assisted_cells)),
      assisted_ratio_by_kind: Object.fromEntries(
        Object.entries(kindMetrics.assisted_cells_by_kind)
          .map(([kind, cells]) => [kind, state.completedCells ? cells / state.completedCells : null]),
      ),
      assisted_per_event_by_kind: kindMetrics.assisted_per_event_by_kind,
      events,
      truncated,
      elapsed_ms: elapsedMs,
    },
  };
}

function average(values) {
  if (!values.length) return null;
  return values.reduce((sum, value) => sum + value, 0) / values.length;
}

function aggregateRunValues(runs, path) {
  const values = [];
  for (const run of runs) {
    const node = path.split('.').reduce((current, part) => current?.[part], run);
    if (node != null && Number.isFinite(Number(node))) values.push(Number(node));
  }
  return values;
}

function summarizeSize(runs) {
  const first = runs[0];
  const gapCells = runs.flatMap((run) => run.route.gaps_cells);
  const gapTargets = runs.flatMap((run) => run.route.gaps_targets);
  const allEvents = runs.flatMap((run) => run.route.events || []);
  const kindNames = [...new Set(allEvents.map((event) => String(event.kind || 'spark')))];
  const placementClusters = runs.map((run) => run.placement.clusters.count);
  const placementCoverage = runs.map((run) => run.placement.region_coverage_ratio);
  const nearestNeighbors = runs.map((run) => run.placement.nearest_neighbor_distance.average);
  const assistedRatios = runs.map((run) => run.route.assisted_ratio);
  const sparkCounts = runs.map((run) => run.placement.spark_count);
  const firstEventKinds = {};
  for (const run of runs) {
    const kind = run.route.first_event_kind;
    if (kind != null) firstEventKinds[kind] = (firstEventKinds[kind] || 0) + 1;
  }
  return {
    size: first.template.width,
    runs: runs.length,
    total_cells: first.template.total_cells,
    colors_total: first.template.colors_total,
    regions_total: first.placement.regions_total,
    spark_count: numericSummary(sparkCounts),
    spark_events: numericSummary(aggregateRunValues(runs, 'route.spark_events')),
    missed_sparks: numericSummary(aggregateRunValues(runs, 'route.missed_sparks')),
    discovery_rate: average(runs.map((run) => run.route.discovery_rate)),
    total_candidates: numericSummary(aggregateRunValues(runs, 'route.total_candidates')),
    total_smart_targets: numericSummary(aggregateRunValues(runs, 'route.total_smart_targets')),
    smart_targets_to_first_spark: numericSummary(aggregateRunValues(runs, 'route.smart_targets_to_first_spark')),
    smart_targets_to_first_event: numericSummary(aggregateRunValues(runs, 'route.smart_targets_to_first_event')),
    first_event_kinds: firstEventKinds,
    events_per_target: average(aggregateRunValues(runs, 'route.events_per_target')),
    events_per_regular_target: average(aggregateRunValues(runs, 'route.events_per_regular_target')),
    gaps_cells: percentileSummary(gapCells),
    gaps_targets: percentileSummary(gapTargets),
    events_by_kind: Object.fromEntries(kindNames.map((kind) => [
      kind,
      numericSummary(runs.map((run) => run.route.events_by_kind?.[kind] || 0)),
    ])),
    type_distribution: Object.fromEntries(kindNames.map((kind) => [
      kind,
      average(runs.map((run) => run.route.type_distribution?.[kind])
        .filter((value) => Number.isFinite(value))),
    ])),
    first_event_by_kind: Object.fromEntries(kindNames.map((kind) => [
      kind,
      numericSummary(runs.map((run) => run.route.first_event_by_kind?.[kind])
        .filter((value) => Number.isFinite(value))),
    ])),
    type_streak_max: numericSummary(
      runs.map((run) => run.route.type_streak?.max).filter((value) => Number.isFinite(value)),
    ),
    type_streak_avg: numericSummary(
      runs.map((run) => run.route.type_streak?.avg).filter((value) => Number.isFinite(value)),
    ),
    type_streak_p95: numericSummary(
      runs.map((run) => run.route.type_streak?.p95).filter((value) => Number.isFinite(value)),
    ),
    type_streak_by_kind: Object.fromEntries(kindNames.map((kind) => [
      kind,
      Math.max(0, ...runs.map((run) => run.route.type_streak?.by_kind?.[kind] || 0)),
    ])),
    gaps_by_kind: Object.fromEntries(kindNames.map((kind) => [kind, {
      cells: percentileSummary(allEvents
        .filter((event) => String(event.kind) === kind)
        .map((event) => event.gap_cells)
        .filter((value) => value != null)),
      targets: percentileSummary(allEvents
        .filter((event) => String(event.kind) === kind)
        .map((event) => event.gap_targets)
        .filter((value) => value != null)),
    }])),
    trap_events: numericSummary(aggregateRunValues(runs, 'route.trap_events')),
    trap_rate: average(runs.map((run) => run.route.trap_rate).filter((value) => value != null)),
    rare_events: numericSummary(aggregateRunValues(runs, 'route.rare_events')),
    rare_rate: average(runs.map((run) => run.route.rare_rate).filter((value) => value != null)),
    assisted_ratio_by_kind: Object.fromEntries(kindNames.map((kind) => [
      kind,
      average(runs.map((run) => run.route.assisted_ratio_by_kind?.[kind])
        .filter((value) => value != null)),
    ])),
    assisted_progress: percentileWithAverage(allEvents.map((event) => (
      event.completed_cells ? Number(event.assisted_cells || 0) / event.completed_cells : 0
    ))),
    clusters: numericSummary(placementClusters),
    region_coverage: average(placementCoverage),
    nearest_neighbor_average: average(nearestNeighbors),
    nearest_neighbor: percentileWithAverage(
      runs.flatMap((run) => run.placement.nearest_neighbor_distance?.distances || []),
    ),
    cluster_size: percentileWithAverage(
      runs.flatMap((run) => run.placement.clusters?.sizes || []),
    ),
    assisted_ratio: average(assistedRatios),
    elapsed_ms: aggregateRunValues(runs, 'route.elapsed_ms').reduce((sum, value) => sum + value, 0),
  };
}

export function summarizeRuns(runs) {
  const bySize = new Map();
  for (const run of runs) bySize.set(run.template.width, [...(bySize.get(run.template.width) || []), run]);
  return {
    per_size: Object.fromEntries(
      [...bySize.entries()]
        .sort((first, second) => first[0] - second[0])
        .map(([size, sizeRuns]) => [size, summarizeSize(sizeRuns)]),
    ),
  };
}

