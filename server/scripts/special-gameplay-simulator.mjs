/**
 * Deterministic hypothetical production pattern when Hazard is added to the
 * shared cadence cycle. Replaces one Spark slot so the V1 mix stays at roughly
 * one Hazard per 20 cycle entries, matching the other rare kinds.
 */
export function hazardAwareKindPattern(pattern = SPECIAL_KIND_PATTERN) {
  return pattern.map((kind, index) => (
    kind === SPARK_KIND && index === 18 ? HAZARD_KIND : kind
  ));
}

/**
 * Adapter around the production kind registry. The simulator never invents
 * kinds silently: production metadata/actions can register Hazard before the
 * generation pattern does, so the report says whether Hazard is active or why
 * it is omitted. Hazard is generated by its own disjoint placer outside the
 * historical mixed cycle.
 */
export function resolveEventKindMix({
  includeHazard = false,
  hazardMode = includeHazard ? 'separate' : 'none',
} = {}) {
  const normalizedMode = HAZARD_MODES.includes(hazardMode) ? hazardMode : (includeHazard ? 'separate' : 'none');
  const productionPattern = [...SPECIAL_KIND_PATTERN];
  const hazardInProductionKinds = (SPECIAL_KINDS || []).includes(HAZARD_KIND);
  const hazardActions = Object.values(SPECIAL_ACTIONS || {})
    .some((action) => String(action?.kind) === HAZARD_KIND);
  // Hazard is production-supported but generated by its own disjoint placer,
  // not by the historical mixed cycle. The pattern/both modes simulate adding
  // Hazard to the cadence pattern without changing production code.
  const pattern = normalizedMode === 'pattern' || normalizedMode === 'both'
    ? hazardAwareKindPattern()
    : productionPattern;
  const activeKinds = normalizedMode === 'none'
    ? [...new Set([...GAMEPLAY_MIX_TYPES, ...pattern])].filter((kind) => kind !== HAZARD_KIND)
    : [...new Set([...GAMEPLAY_MIX_TYPES, ...pattern])];
  return {
    source: normalizedMode === 'pattern' || normalizedMode === 'both'
      ? 'simulator-pattern-fixture'
      : 'production',
    generation_version: SPECIAL_GAMEPLAY_GENERATION_VERSION,
    pattern,
    hazard_mode: normalizedMode,
    active_kinds: activeKinds,
    production: {
      kinds: [...(SPECIAL_KINDS || [])],
      pattern: productionPattern,
      hazard_registered: Boolean(SPECIAL_KIND_META?.[HAZARD_KIND]),
      hazard_in_active_kinds: hazardInProductionKinds,
      hazard_in_pattern: false,
      hazard_actions_supported: hazardActions,
    },
    hazard: {
      kind: HAZARD_KIND,
      included: normalizedMode !== 'none',
      omitted: normalizedMode === 'none',
      mode: normalizedMode,
      reason: normalizedMode === 'none'
        ? 'production hazard generation is disabled for this run'
        : normalizedMode === 'separate'
          ? 'production registers hazard and generates it with a disjoint placer outside the historical kind cycle'
          : normalizedMode === 'pattern'
            ? 'simulating one Hazard slot in the shared cadence pattern without the separate hazard row'
            : 'simulating one Hazard slot in the shared cadence pattern plus the separate disjoint hazard row',
    },
  };
}

function fnv1a(value) {
  let hash = 2166136261;
  for (const character of String(value)) {
    hash ^= character.charCodeAt(0);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function mulberry32(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

export function percentile(values, p) {
  if (!values.length) return null;
  const sorted = [...values].sort((first, second) => first - second);
  const index = Math.min(sorted.length - 1, Math.max(0, Math.ceil((p / 100) * sorted.length) - 1));
  return sorted[index];
}

export function percentileSummary(values, percentiles = [50, 90, 95]) {
  const summary = {
    count: values.length,
    min: values.length ? Math.min(...values) : null,
    max: values.length ? Math.max(...values) : null,
  };
  for (const p of percentiles) summary[`p${p}`] = percentile(values, p);
  return summary;
}

export function percentileWithAverage(values, percentiles = [50, 90, 95]) {
  const summary = percentileSummary(values, percentiles);
  return {
    ...summary,
    avg: values.length
      ? values.reduce((total, value) => total + value, 0) / values.length
      : null,
  };
}

/**
 * Kind-aware summaries over discovered special events. The default Spark-only
 * baseline keeps the existing route summaries; event-mix runs also report
 * per-kind counts, streaks, gaps, trap/rare rates, and assisted cells.
 */
export function summarizeKindEventMetrics(events = []) {
  const counts = {};
  const assistedCellsByKind = {};
  const gapCellsByKind = {};
  const gapTargetsByKind = {};
  const firstPlanIndexByKind = {};
  let previousKind = null;
  let currentStreak = 0;
  let maxStreak = 0;
  const longestStreakByKind = {};
  const streakLengths = [];
  for (const event of events) {
    const kind = String(event.kind || SPARK_KIND);
    counts[kind] = (counts[kind] || 0) + 1;
    assistedCellsByKind[kind] = (assistedCellsByKind[kind] || 0) + Number(event.assisted_cells || 0);
    if (firstPlanIndexByKind[kind] == null) firstPlanIndexByKind[kind] = Number(event.plan_index);
    if (event.gap_cells != null) {
      gapCellsByKind[kind] ||= [];
      gapCellsByKind[kind].push(event.gap_cells);
    }
    if (event.gap_targets != null) {
      gapTargetsByKind[kind] ||= [];
      gapTargetsByKind[kind].push(event.gap_targets);
    }
    if (kind === previousKind) {
      currentStreak += 1;
    } else {
      if (currentStreak > 0) streakLengths.push(currentStreak);
      currentStreak = 1;
      previousKind = kind;
    }
    maxStreak = Math.max(maxStreak, currentStreak);
    longestStreakByKind[kind] = Math.max(longestStreakByKind[kind] || 0, currentStreak);
  }
  if (currentStreak > 0) streakLengths.push(currentStreak);
  const kinds = Object.keys(counts);
  const trapEvents = events.filter((event) => TRAP_KINDS.includes(String(event.kind))).length;
  const rareEvents = events.filter((event) => RARE_KINDS.includes(String(event.kind))).length;
  return {
    events_by_kind: counts,
    type_distribution: Object.fromEntries(kinds.map((kind) => [
      kind,
      events.length ? counts[kind] / events.length : null,
    ])),
    first_event_by_kind: firstPlanIndexByKind,
    type_streak: {
      max: maxStreak,
      avg: streakLengths.length
        ? streakLengths.reduce((sum, value) => sum + value, 0) / streakLengths.length
        : null,
      p95: percentile(streakLengths, 95),
      by_kind: longestStreakByKind,
    },
    gaps_by_kind: Object.fromEntries(kinds.map((kind) => [kind, {
      count: (gapCellsByKind[kind] || []).length,
      cells_summary: percentileSummary(gapCellsByKind[kind] || []),
      targets_summary: percentileSummary(gapTargetsByKind[kind] || []),
    }])),
    trap_events: trapEvents,
    trap_rate: events.length ? trapEvents / events.length : null,
    rare_events: rareEvents,
    rare_rate: events.length ? rareEvents / events.length : null,
    assisted_cells_by_kind: assistedCellsByKind,
    assisted_progress: percentileWithAverage(events.map((event) => (
      event.completed_cells ? Number(event.assisted_cells || 0) / event.completed_cells : 0
    ))),
    assisted_per_event_by_kind: Object.fromEntries(kinds.map((kind) => [
      kind,
      numericSummary(events.filter((event) => String(event.kind) === kind).map((event) => event.assisted_cells)),
    ])),
  };
}

export function numericSummary(values) {
  if (!values.length) return { count: 0, min: null, avg: null, max: null };
  const sum = values.reduce((total, value) => total + value, 0);
  return {
    count: values.length,
    min: Math.min(...values),
    avg: sum / values.length,
    max: Math.max(...values),
  };
}

